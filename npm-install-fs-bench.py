def tree_metrics(node_modules: Path) -> dict[str, int]:
    metrics = {
        "files": 0,
        "dirs": 0,
        "symlinks": 0,
        "hardlinks": 0,
        "logical_bytes": 0,
        "allocated_bytes": 0,
        "du_kib": 0,
    }
    if not node_modules.is_dir():
        return metrics

    seen_allocated_inodes: set[tuple[int, int]] = set()
    metrics["dirs"] = 1
    stack = [node_modules]
    while stack:
        current = stack.pop()
        try:
            entries = list(os.scandir(current))
        except OSError:
            continue
        for entry in entries:
            try:
                stat_result = entry.stat(follow_symlinks=False)
            except OSError:
                continue
            mode = stat_result.st_mode
            if os.path.islink(entry.path):
                metrics["symlinks"] += 1
            elif os.path.isdir(entry.path):
                metrics["dirs"] += 1
                stack.append(Path(entry.path))
            elif os.path.isfile(entry.path):
                metrics["files"] += 1
                metrics["logical_bytes"] += stat_result.st_size
                if stat_result.st_nlink > 1:
                    inode = (stat_result.st_dev, stat_result.st_ino)
                    counted = inode not in seen_allocated_inodes
                    seen_allocated_inodes.add(inode)
                else:
                    counted = True
                if counted:
                    metrics["allocated_bytes"] += (
                        getattr(stat_result, "st_blocks", 0) or 0
                    ) * 512
                if stat_result.st_nlink > 1:
                    metrics["hardlinks"] += 1

    try:
        result = subprocess.run(
            ["du", "-sk", str(node_modules)],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            check=False,
        )
        if result.stdout.strip():
            metrics["du_kib"] = int(result.stdout.split()[0])
    except (OSError, ValueError):
        metrics["du_kib"] = metrics["allocated_bytes"] // 1024

    return metrics


def prepare_project(
    root: Path,
    manager: str,
    run_number: int,
    template_dir: Path,
) -> Path:
    # Keep run projects as siblings of the seed projects. This preserves the
    # meaning of relative file: package specs copied from package.json.
    project = root / "work" / f"{manager}-run-{run_number}"
    ensure_dir(project)
    shutil.copy2(template_dir / "package.json", project / "package.json")
    if manager == "npm":
        shutil.copy2(template_dir / "package-lock.json", project / "package-lock.json")
    else:
        shutil.copy2(template_dir / "pnpm-lock.yaml", project / "pnpm-lock.yaml")
    remove_tree(project / "node_modules")
    return project


def read_tail(path: Path, line_count: int = 20) -> str:
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return ""
    return "\n".join(lines[-line_count:])


def run_timed(
    command: list[str],
    cwd: Path,
    log_path: Path,
    env: dict[str, str] | None = None,
) -> tuple[int, float, float, float]:
    before = resource.getrusage(resource.RUSAGE_CHILDREN)
    started = time.monotonic()
    try:
        with log_path.open("w", encoding="utf-8") as log_handle:
            result = subprocess.run(
                command,
                cwd=str(cwd),
                env=env,
                stdout=log_handle,
                stderr=subprocess.STDOUT,
                check=False,
            )
        status = result.returncode
    except OSError as exc:
        log_path.write_text(f"{exc}\n", encoding="utf-8")
        status = 1
    elapsed = time.monotonic() - started
    after = resource.getrusage(resource.RUSAGE_CHILDREN)
    user = max(0.0, after.ru_utime - before.ru_utime)
    system = max(0.0, after.ru_stime - before.ru_stime)
    return status, elapsed, user, system


def finalize_run(
    project: Path, keep_node_modules: bool
) -> tuple[float, int, dict[str, int]]:
    """Flush the tree, measure it while it exists, then drop it."""
    node_modules = project / "node_modules"
    sync_s, sync_errors = fsync_tree(node_modules)
    metrics = tree_metrics(node_modules)
    if sync_errors:
        log(
            f"fsync reported {sync_errors} error(s) under {node_modules}; "
            "see the sync_errors column"
        )
    if not keep_node_modules:
        remove_tree(node_modules)
    sync_filesystem()
    return sync_s, sync_errors, metrics


def make_result(
    manager: str,
    run_number: int,
    status: int,
    elapsed: float,
    sync_s: float,
    sync_errors: int,
    user: float,
    system: float,
    metrics: dict[str, int],
    log_name: str,
) -> dict[str, object]:
    elapsed_for_rate = elapsed if elapsed > 0 else 0.0
    files_per_s = metrics["files"] / elapsed_for_rate if elapsed_for_rate else 0.0
    logical_mib_s = (
        (metrics["logical_bytes"] / 1048576.0) / elapsed_for_rate
        if elapsed_for_rate
        else 0.0
    )
    allocated_mib_s = (
        (metrics["allocated_bytes"] / 1048576.0) / elapsed_for_rate
        if elapsed_for_rate
        else 0.0
    )
    sync_for_rate = sync_s if sync_s > 0 else 0.0
    sync_files_per_s = (
        metrics["files"] / sync_for_rate if sync_for_rate else 0.0
    )
    return {
        "manager": manager,
        "run": run_number,
        "status": "ok" if status == 0 else "failed",
        "elapsed_s": f"{elapsed:.6f}",
        "sync_s": f"{sync_s:.6f}",
        "sync_errors": sync_errors,
        "user_s": f"{user:.6f}",
        "sys_s": f"{system:.6f}",
        **metrics,
        "files_per_s": f"{files_per_s:.3f}",
        "sync_files_per_s": f"{sync_files_per_s:.3f}",
        "logical_mib_per_s": f"{logical_mib_s:.3f}",
        "allocated_mib_per_s": f"{allocated_mib_s:.3f}",
        "log": log_name,
    }


def run_npm_once(
    args: argparse.Namespace,
    root: Path,
    results_dir: Path,
    npm_bin: str,
    cache_dir: Path,
    template_dir: Path,
    run_number: int,
) -> dict[str, object]:
    project = prepare_project(root, "npm", run_number, template_dir)
    log_path = results_dir / "logs" / f"npm-run-{run_number}.log"
    if args.warm_each_run:
        warm_tree(cache_dir)

    command = [
        npm_bin,
        "install",
        "--offline",
        "--cache",
        str(cache_dir),
        "--no-audit",
        "--no-fund",
        "--no-update-notifier",
        *ignore_args("npm", args.ignore_scripts),
    ]
    log(f"npm run {run_number}/{args.runs} on {project}")
    status, elapsed, user, system = run_timed(command, project, log_path)
    sync_s, sync_errors, metrics = finalize_run(project, args.keep_node_modules)
    row = make_result(
        "npm",
        run_number,
        status,
        elapsed,
        sync_s,
        sync_errors,
        user,
        system,
        metrics,
        log_path.name,
    )
    if status != 0:
        log(f"npm run {run_number} failed; see {log_path}")
        tail = read_tail(log_path)
        if tail:
            print(tail, file=sys.stderr)
    return row


