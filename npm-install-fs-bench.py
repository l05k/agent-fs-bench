def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_FIELDS, lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row[field] for field in CSV_FIELDS})


def write_summary(path: Path, rows: list[dict[str, object]], managers: list[str]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["manager", "ok_runs", "mean_s", "median_s", "p95_s"])
        for manager in managers:
            values = sorted(
                float(row["elapsed_s"])
                for row in rows
                if row["manager"] == manager and row["status"] == "ok"
            )
            if not values:
                continue
            p95_index = max(0, math.ceil(0.95 * len(values)) - 1)
            writer.writerow(
                [
                    manager,
                    len(values),
                    f"{statistics.mean(values):.6f}",
                    f"{statistics.median(values):.6f}",
                    f"{values[p95_index]:.6f}",
                ]
            )


def download_package_catalog(url: str, destination: Path) -> list[str]:
    log(f"downloading package catalog: {url}")
    request = urlrequest.Request(
        url,
        headers={"User-Agent": "npm-install-fs-bench/1.0"},
    )
    try:
        with urlrequest.urlopen(request, timeout=30) as response:
            raw = response.read()
    except (urlerror.URLError, TimeoutError, OSError) as exc:
        die(f"failed to download package catalog from {url}: {exc}")

    destination.write_bytes(raw)
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        die(f"package catalog is not valid UTF-8: {exc}")

    reader = csv.DictReader(io.StringIO(text))
    if not reader.fieldnames or "package" not in reader.fieldnames:
        die("package catalog must be CSV with a 'package' column")

    ranked_packages: list[tuple[int, str]] = []
    for index, row in enumerate(reader, start=1):
        package = (row.get("package") or "").strip()
        if not package:
            continue
        try:
            rank = int((row.get("rank") or "").strip())
        except ValueError:
            rank = index
        ranked_packages.append((rank, package))

    if not ranked_packages:
        die("package catalog is empty")
    ranked_packages.sort(key=lambda item: item[0])

    packages = [package for _rank, package in ranked_packages]
    if len(set(packages)) != len(packages):
        die("package catalog contains duplicate package names")
    log(f"downloaded {len(packages)} package entries")
    return packages


def parse_packages(
    raw: list[str] | None,
    top_k: int,
    catalog: list[str],
) -> list[str]:
    if raw:
        packages: list[str] = []
        for chunk in raw:
            for item in chunk.split(","):
                item = item.strip()
                if item and item not in packages:
                    packages.append(item)
    else:
        if top_k < 1 or top_k > len(catalog):
            die(f"--top-k must be between 1 and {len(catalog)}")
        packages = catalog[:top_k]

    if not packages:
        die("package selection is empty")
    for package in packages:
        if package.startswith("-"):
            die(f"package specs must not start with '-': {package}")
        if any(character.isspace() for character in package):
            die(f"package specs must not contain whitespace: {package}")
    return packages


