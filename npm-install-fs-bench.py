def main(argv: list[str]) -> int:
    args = parse_args(argv)
    target_dir = ensure_dir(args.target_dir)
    # Intermediate artifacts must live on the filesystem under test.
    root = Path(tempfile.mkdtemp(prefix="npm-install-bench-", dir=str(target_dir)))
    # Only reports, logs and manifests go to the project results directory.
    results_dir = results_run_dir(SCRIPT_NAME, anchor=__file__)

    cache_root = root / "cache"
    npm_cache = ensure_dir(args.cache_dir) if args.cache_dir else ensure_dir(cache_root / "npm")
    pnpm_store = ensure_dir(args.store_dir) if args.store_dir else ensure_dir(cache_root / "pnpm")
    pnpm_cache = ensure_dir(cache_root / "pnpm-xdg")

    templates_root = root / "templates"
    npm_template = ensure_dir(templates_root / "npm")
    pnpm_template = ensure_dir(templates_root / "pnpm")
    work_root = ensure_dir(root / "work")
    seed_npm_dir = work_root / "seed-npm"
    seed_pnpm_dir = work_root / "seed-pnpm"
    resolve_dir = work_root / "resolve"
    logs_dir = ensure_dir(results_dir / "logs")

    catalog: list[str] = []
    catalog_path: Path | None = None
    package_list_source = "custom --packages"
    if args.packages:
        packages = parse_packages(args.packages, args.top_k, catalog)
    else:
        package_list_source = "gist"
        catalog_path = results_dir / "top-packages.csv"
        catalog = download_package_catalog(PACKAGE_LIST_URL, catalog_path)
        packages = parse_packages(None, args.top_k, catalog)

    selected_path = results_dir / "selected-packages.txt"
    selected_path.write_text("\n".join(packages) + "\n", encoding="utf-8")

    npm_bin = resolve_tool(args.npm_bin, "npm")
    pnpm_bin = ""
    if args.pm in ("pnpm", "both"):
        pnpm_bin = resolve_tool(args.pnpm_bin, "pnpm")

    npm_version = command_version(npm_bin, timeout=10.0) or "unknown"
    pnpm_version = "not selected"
    if pnpm_bin:
        pnpm_version = command_version(pnpm_bin, timeout=10.0)
        if not pnpm_version:
            die("pnpm --version failed; check --pnpm-bin and the pnpm installation")

    node_version = "unknown"
    node_bin = shutil.which("node")
    if node_bin:
        node_version = command_version(str(Path(node_bin).resolve()), timeout=10.0) or "unknown"

    os_name = platform.system() or "unknown"
    os_release = platform.release() or "unknown"
    created_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    df_line = ""
    try:
        df_result = subprocess.run(
            ["df", "-P", str(target_dir)],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            check=False,
        )
        df_lines = df_result.stdout.splitlines()
        if len(df_lines) > 1:
            df_line = df_lines[1]
    except OSError:
        pass

    manifest_path = results_dir / "manifest.txt"
    manifest_lines = [
        f"root={root}",
        f"target_dir={target_dir}",
        f"work_dir={work_root}",
        f"created_at_utc={created_at}",
        f"selected_packages={len(packages)}",
        f"package_list_source={package_list_source}",
        f"package_list_url={PACKAGE_LIST_URL if catalog_path else 'not fetched'}",
        f"package_list_file={catalog_path or 'not downloaded'}",
        f"package_list_entries={len(catalog)}",
        f"selected_packages_file={selected_path}",
        f"package_manager_mode={args.pm}",
        f"node={node_version}",
        f"npm={npm_version}",
        f"pnpm={pnpm_version}",
        f"os={os_name}",
        f"os_release={os_release}",
        f"target_df={df_line}",
        f"npm_cache={npm_cache}",
        f"pnpm_store={pnpm_store}",
        f"pnpm_cache={pnpm_cache}",
        f"npm_package_json={npm_template / 'package.json'}",
        f"npm_lockfile={npm_template / 'package-lock.json'}",
        f"pnpm_package_json={pnpm_template / 'package.json'}",
        f"pnpm_lockfile={pnpm_template / 'pnpm-lock.yaml'}",
        f"ignore_scripts={int(args.ignore_scripts)}",
        f"prewarm={int(not args.no_prewarm)}",
        f"warm_each_run={int(args.warm_each_run)}",
        f"keep_node_modules={int(args.keep_node_modules)}",
        f"pnpm_import_method={args.pnpm_import_method}",
        "pnpm_global_virtual_store=0",
        "timed_command_npm=npm install --offline",
        (
            "timed_command_pnpm=pnpm install --offline "
            f"--package-import-method={args.pnpm_import_method} "
            "--config.enable-global-virtual-store=false"
        ),
        "note=warm cache/store; cold node_modules; cache/store reads are warmed; "
        "scripts enabled unless --ignore-scripts; logical_bytes counts file entries; "
        "allocated_bytes counts each hardlinked inode once",
    ]
    manifest_path.write_text("\n".join(manifest_lines) + "\n", encoding="utf-8")

    if args.pm in ("npm", "both"):
        seed_npm(
            npm_bin,
            npm_cache,
            seed_npm_dir,
            npm_template,
            packages,
            args.ignore_scripts,
        )
    elif args.pm == "pnpm":
        resolve_pnpm_packages(
            npm_bin,
            npm_cache,
            resolve_dir,
            pnpm_template,
            packages,
            args.ignore_scripts,
        )
    if args.pm == "both":
        shutil.copy2(
            npm_template / "package.json",
            pnpm_template / "package.json",
        )
    if args.pm in ("pnpm", "both"):
        seed_pnpm(
            pnpm_bin,
            pnpm_store,
            pnpm_cache,
            seed_pnpm_dir,
            pnpm_template,
            args.pnpm_import_method,
            args.ignore_scripts,
        )

    if not args.no_prewarm:
        if args.pm in ("npm", "both"):
            warm_tree(npm_cache)
        if args.pm in ("pnpm", "both"):
            warm_tree(pnpm_store)
            warm_tree(pnpm_cache)

    log("flushing seed/cache writes before timed runs")
    sync_filesystem()

    if args.seed_only:
        log("seed complete; timed runs skipped (--seed-only)")
        log(f"root: {root}")
        return 0

    managers = []
    if args.pm in ("npm", "both"):
        managers.append("npm")
    if args.pm in ("pnpm", "both"):
        managers.append("pnpm")

    rows: list[dict[str, object]] = []
    for manager in managers:
        for run_number in range(1, args.runs + 1):
            if manager == "npm":
                row = run_npm_once(
                    args,
                    root,
                    results_dir,
                    npm_bin,
                    npm_cache,
                    npm_template,
                    run_number,
                )
            else:
                row = run_pnpm_once(
                    args,
                    root,
                    results_dir,
                    pnpm_bin,
                    pnpm_store,
                    pnpm_cache,
                    pnpm_template,
                    run_number,
                )
            rows.append(row)

    results_path = results_dir / "results.csv"
    summary_path = results_dir / "summary.csv"
    write_csv(results_path, rows)
    write_summary(summary_path, rows, managers)

    log(f"results: {results_path}")
    log(f"summary: {summary_path}")
    log(f"manifest: {manifest_path}")
    log(f"benchmark root: {root}")
    return 0


