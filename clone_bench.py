def comma_names(value: str) -> list[str]:
    return [part.strip() for part in value.split(",") if part.strip()]


def _mountinfo_unescape(value: str) -> str:
    return re.sub(
        r"\\([0-7]{3})",
        lambda match: chr(int(match.group(1), 8)),
        value,
    )


def _fstype_from_mountinfo(path: str) -> str | None:
    try:
        with open("/proc/self/mountinfo", encoding="utf-8") as fh:
            entries = fh.readlines()
    except OSError:
        return None
    best_mount = ""
    best_type = None
    for line in entries:
        before, separator, after = line.partition(" - ")
        if not separator:
            continue
        fields = before.split()
        if len(fields) < 5:
            continue
        mount_point = _mountinfo_unescape(fields[4]).rstrip("/") or "/"
        fs_type = after.split()[0] if after.split() else ""
        if not fs_type:
            continue
        if path == mount_point or path.startswith(mount_point.rstrip("/") + "/"):
            if len(mount_point) >= len(best_mount):
                best_mount = mount_point
                best_type = fs_type
    return best_type


def fstype(path: str) -> str:
    """Return the filesystem type, or ``unknown`` when no probe works."""
    path = os.path.realpath(os.path.abspath(path))
    proc_type = _fstype_from_mountinfo(path)
    if proc_type:
        return proc_type
    findmnt = shutil.which("findmnt")
    if findmnt:
        try:
            return subprocess.check_output(
                [findmnt, "-no", "FSTYPE", "-T", path],
                text=True,
                stderr=subprocess.DEVNULL,
            ).strip() or "unknown"
        except (OSError, subprocess.CalledProcessError):
            pass
    stat = shutil.which("stat")
    if stat:
        try:
            return subprocess.check_output(
                [stat, "-f", "-c", "%T", path],
                text=True,
                stderr=subprocess.DEVNULL,
            ).strip() or "unknown"
        except (OSError, subprocess.CalledProcessError):
            pass
    return "unknown"


def fsync_dir(path: str) -> None:
    flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0)
    fd = os.open(path, flags)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def fsync_file(path: str) -> None:
    # fsync through a read-only fd flushes the inode's dirty pages on Linux.
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def fsync_tree(path: str) -> None:
    for root, _dirs, files in os.walk(path):
        for name in files:
            fsync_file(os.path.join(root, name))
        fsync_dir(root)


