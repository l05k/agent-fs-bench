def estimated_need(spec: dict[str, Any]) -> int:
    if spec["kind"] == "large":
        data_bytes = spec["total_bytes"]
        files = spec.get("shards", spec["concurrency"])
    else:
        data_bytes = spec["count"] * spec["file_size"]
        files = spec["count"]
    return data_bytes * 2 + 256 * MIB + files * 4096


class CsvSink:
    """Write to this run's raw.csv and optionally append to a shared CSV."""

    def __init__(self, raw_path: Path, append_path: str = "") -> None:
        append = Path(append_path).expanduser() if append_path else None
        append_is_new = False
        if append is not None:
            if append.resolve() == raw_path.resolve():
                raise BenchmarkError(
                    "--append-csv must differ from this run's raw.csv"
                )
            append.parent.mkdir(parents=True, exist_ok=True)
            append_is_new = not append.exists() or append.stat().st_size == 0
            if not append_is_new:
                with append.open(newline="", encoding="utf-8") as check_fh:
                    header = next(csv.reader(check_fh), None)
                if header != CSV_FIELDS:
                    raise BenchmarkError(
                        f"{append} has a different CSV schema; refusing to append"
                    )

        self.raw_fh = raw_path.open("w", newline="", encoding="utf-8")
        self.raw_writer = csv.DictWriter(self.raw_fh, fieldnames=CSV_FIELDS)
        self.raw_writer.writeheader()
        self.append_fh = None
        self.append_writer = None
        if append is not None:
            self.append_fh = append.open("a", newline="", encoding="utf-8")
            self.append_writer = csv.DictWriter(
                self.append_fh, fieldnames=CSV_FIELDS
            )
            if append_is_new:
                self.append_writer.writeheader()

    def write(self, row: dict[str, Any]) -> None:
        self.raw_writer.writerow(row)
        self.raw_fh.flush()
        if self.append_writer is not None:
            self.append_writer.writerow(row)
            self.append_fh.flush()

    def close(self) -> None:
        self.raw_fh.close()
        if self.append_fh is not None:
            self.append_fh.close()

    def __enter__(self) -> "CsvSink":
        return self

    def __exit__(self, exc_type: Any, exc: Any, tb: Any) -> None:
        self.close()


def run_case(
    mount: str,
    spec: dict[str, Any],
    args: argparse.Namespace,
    sink: CsvSink,
    run_id: str,
    copiers: Sequence[Copier],
    cp_binary: str,
) -> list[dict[str, Any]]:
    workload = spec["workload"]
    concurrency = spec["concurrency"]
    scratch = os.path.join(mount, args.scratch_subpath, run_id)
    source_root = os.path.join(scratch, f"src_{workload}_C{concurrency}")
    destination_root = os.path.join(scratch, f"dst_{workload}_C{concurrency}")
    need = estimated_need(spec)
    free = shutil.disk_usage(mount).free
    if free < need:
        log(
            f"[{mount}] SKIP {workload} C={concurrency}: "
            f"free {free / MIB:.0f} MiB < need {need / MIB:.0f} MiB"
        )
        return []

    rows: list[dict[str, Any]] = []
    fs_type = fstype(mount)
    shutil.rmtree(source_root, ignore_errors=True)
    shutil.rmtree(destination_root, ignore_errors=True)
    try:
        os.makedirs(source_root, exist_ok=True)
        log(f"[{mount}] generate {workload} C={concurrency} ...")
        shards = gen_dataset(spec, source_root, args.data_pattern)
        total_bytes, total_files = dataset_bytes_files(shards)
        inventories = {shard: tree_inventory(shard) for shard in shards}
        log(
            f"[{mount}] {workload} C={concurrency}: "
            f"{total_bytes / MIB:.1f} MiB in {total_files} files"
        )
        warm_source(shards, total_bytes)
        log(
            f"[{mount}] {workload} C={concurrency}: "
            "source pre-read complete (warm cache, best effort)"
        )

        for copier in copiers:
            for repeat in range(1, args.repeats + 1):
                shutil.rmtree(destination_root, ignore_errors=True)
                os.makedirs(destination_root, exist_ok=True)
                wall, copy_seconds, fsync_seconds = copy_shards(
                    shards,
                    destination_root,
                    copier,
                    args.fsync,
                    args.threads,
                    cp_binary,
                )
                for index, shard in enumerate(shards):
                    verify_tree(
                        shard,
                        os.path.join(destination_root, f"shard_{index}"),
                        inventories[shard],
                    )
                mib_s = total_bytes / MIB / wall if wall > 0 else 0.0
                files_s = total_files / wall if wall > 0 else 0.0
                row = {
                    "ts": int(time.time()),
                    "run_id": run_id,
                    "mount": mount,
                    "fstype": fs_type,
                    "workload": workload,
                    "kind": spec["kind"],
                    "concurrency": concurrency,
                    "threads": args.threads,
                    "total_bytes": total_bytes,
                    "total_files": total_files,
                    "data_pattern": args.data_pattern,
                    "copier": copier.name,
                    "fsync": int(args.fsync),
                    "cache_state": CACHE_STATE,
                    "repeat": repeat,
                    "wall_s": round(wall, 6),
                    "copy_s": round(copy_seconds, 6),
                    "fsync_s": round(fsync_seconds, 6),
                    "mib_s": round(mib_s, 3),
                    "files_s": round(files_s, 3),
                    "verified": 1,
                }
                sink.write(row)
                rows.append(row)
                log(
                    f"[{mount}] {workload} C={concurrency} {copier.name} "
                    f"rep{repeat}: wall={wall:.3f}s copy={copy_seconds:.3f}s "
                    f"fsync={fsync_seconds:.3f}s -> {mib_s:.1f} MiB/s, "
                    f"{files_s:.0f} files/s (verified)"
                )
    finally:
        if args.keep_scratch:
            log(
                f"[{mount}] keeping scratch: {source_root}, {destination_root}"
            )
        else:
            shutil.rmtree(source_root, ignore_errors=True)
            shutil.rmtree(destination_root, ignore_errors=True)
    return rows


def build_plan(
    stage: str,
    smoke: bool,
    small_count: int,
    concurrency_levels: Sequence[int],
) -> list[dict[str, Any]]:
    if smoke:
        return [
            {
                "workload": "smoke_L8M",
                "kind": "large",
                "concurrency": 1,
                "total_bytes": 8 * MIB,
            },
            {
                "workload": "smoke_S200_x8K",
                "kind": "small",
                "concurrency": 1,
                "count": 200,
                "file_size": 8 * 1024,
            },
            {
                "workload": "smoke_L16M",
                "kind": "large",
                "concurrency": 4,
                "total_bytes": 16 * MIB,
            },
            {
                "workload": "smoke_S400_x8K",
                "kind": "small",
                "concurrency": 4,
                "count": 400,
                "file_size": 8 * 1024,
            },
        ]

    plan: list[dict[str, Any]] = []
    small_prefix = f"S{small_count}"
    if stage in ("single", "all"):
        plan.extend(
            [
                {
                    "workload": "L256M",
                    "kind": "large",
                    "concurrency": 1,
                    "total_bytes": 256 * MIB,
                },
                {
                    "workload": "L1G",
                    "kind": "large",
                    "concurrency": 1,
                    "total_bytes": 1 * GIB,
                },
                {
                    "workload": f"{small_prefix}_x4K",
                    "kind": "small",
                    "concurrency": 1,
                    "count": small_count,
                    "file_size": 4 * 1024,
                },
                {
                    "workload": f"{small_prefix}_x64K",
                    "kind": "small",
                    "concurrency": 1,
                    "count": small_count,
                    "file_size": 64 * 1024,
                },
            ]
        )
    if stage in ("concurrency", "all"):
        for concurrency in concurrency_levels:
            plan.extend(
                [
                    {
                        "workload": "Ltotal2G",
                        "kind": "large",
                        "concurrency": concurrency,
                        "total_bytes": 2 * GIB,
                    },
                    {
                        "workload": f"{small_prefix}_x64K",
                        "kind": "small",
                        "concurrency": concurrency,
                        "count": small_count,
                        "file_size": 64 * 1024,
                    },
                ]
            )
    return plan


def filter_plan(plan: list[dict[str, Any]], kinds: str) -> list[dict[str, Any]]:
    if not kinds:
        return plan
    keep = set(comma_names(kinds))
    unknown = keep - {"large", "small"}
    if unknown:
        raise BenchmarkError(
            "unknown --kinds value(s): " + ", ".join(sorted(unknown))
        )
    return [spec for spec in plan if spec["kind"] in keep]


def dedupe_plan(plan: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Drop repeated specs produced by overlapping stages such as ``all``."""
    unique: list[dict[str, Any]] = []
    seen: set[tuple[Any, ...]] = set()
    for spec in plan:
        key = (
            spec["workload"],
            spec["kind"],
            spec["concurrency"],
            spec.get("total_bytes"),
            spec.get("count"),
            spec.get("file_size"),
            spec.get("shards"),
        )
        if key in seen:
            continue
        seen.add(key)
        unique.append(spec)
    return unique


def median(values: Sequence[float]) -> float:
    ordered = sorted(values)
    count = len(ordered)
    if count == 0:
        return 0.0
    if count % 2:
        return ordered[count // 2]
    return (ordered[count // 2 - 1] + ordered[count // 2]) / 2


# ------------------------------- reporting ---------------------------------


def metric_field(kind: str) -> tuple[str, str]:
    return ("mib_s", "MiB/s") if kind == "large" else ("files_s", "files/s")


def format_bytes(value: int) -> str:
    if value >= GIB:
        return f"{value / GIB:.2f}GiB"
    if value >= MIB:
        return f"{value / MIB:.0f}MiB"
    return f"{value / 1024:.0f}KiB"


def load_rows(path: str) -> list[dict[str, str]]:
    with open(path, newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        if reader.fieldnames != CSV_FIELDS:
            raise BenchmarkError(
                f"{path} has an unexpected CSV schema; expected "
                + ",".join(CSV_FIELDS)
            )
        return list(reader)


def aggregate_rows(
    rows: Sequence[dict[str, str]],
) -> dict[tuple[Any, ...], dict[str, Any]]:
    groups: dict[tuple[Any, ...], list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        key = (
            row["mount"],
            row["workload"],
            row["kind"],
            int(row["concurrency"]),
            row["copier"],
            int(row["fsync"]),
            row["cache_state"],
            row["data_pattern"],
        )
        groups[key].append(row)

    aggregates: dict[tuple[Any, ...], dict[str, Any]] = {}
    for key, group in groups.items():
        field, unit = metric_field(key[2])
        metrics = [float(row[field]) for row in group]
        walls = [float(row["wall_s"]) for row in group]
        copies = [float(row["copy_s"]) for row in group]
        fsyncs = [float(row["fsync_s"]) for row in group]
        aggregates[key] = {
            "n": len(group),
            "metric": median(metrics),
            "metric_min": min(metrics),
            "metric_max": max(metrics),
            "wall": median(walls),
            "copy": median(copies),
            "fsync": median(fsyncs),
            "bytes": int(group[0]["total_bytes"]),
            "files": int(group[0]["total_files"]),
            "unit": unit,
        }
    return aggregates


def render_report(rows: Sequence[dict[str, str]]) -> str:
    if not rows:
        return "# Same-filesystem copy benchmark\n\nNo rows.\n"

    aggregates = aggregate_rows(rows)
    mounts: list[str] = []
    copiers: list[str] = []
    for row in rows:
        if row["mount"] not in mounts:
            mounts.append(row["mount"])
        if row["copier"] not in copiers:
            copiers.append(row["copier"])
    mount_types = {
        row["mount"]: row["fstype"] for row in rows
    }
    fsync_modes = sorted({int(row["fsync"]) for row in rows})
    cache_states = sorted({row["cache_state"] for row in rows})
    data_patterns = sorted({row["data_pattern"] for row in rows})
    kind_order = {"large": 0, "small": 1}

    def key_order(key: tuple[Any, ...]) -> tuple[Any, ...]:
        (
            mount,
            workload,
            kind,
            concurrency,
            copier,
            fsync,
            cache_state,
            data_pattern,
        ) = key
        return (
            mounts.index(mount),
            kind_order.get(kind, 9),
            workload,
            concurrency,
            copiers.index(copier),
            fsync,
            cache_state,
            data_pattern,
        )

    keys = sorted(aggregates, key=key_order)
    lines = [
        "# Same-filesystem copy/clone benchmark",
        "",
        "Cache state: **warm-source-preread** (no cold-cache mode). "
        "Large workloads use logical payload MiB/s; small-file workloads use "
        "files/s. Both divide the payload by the full copy wall time.",
        "",
        f"Mounts: {', '.join(f'{mount} ({mount_types[mount]})' for mount in mounts)}  ",
        f"Copiers: {', '.join(copiers)}  ",
        f"fsync: {', '.join('on' if value else 'off' for value in fsync_modes)}  ",
        f"Cache state(s): {', '.join(cache_states)}  ",
        f"Data pattern(s): {', '.join(data_patterns)}",
        "",
        "## Detail",
        "",
        "| mount | workload | kind | C | copier | fsync | pattern | data | files | n "
        "| wall med (s) | copy med (s) | fsync med (s) | metric med (min-max) |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for key in keys:
        (
            mount,
            workload,
            kind,
            concurrency,
            copier,
            fsync,
            _cache_state,
            data_pattern,
        ) = key
        item = aggregates[key]
        lines.append(
            f"| {mount} | {workload} | {kind} | {concurrency} | {copier} "
            f"| {'on' if fsync else 'off'} | {data_pattern} "
            f"| {format_bytes(item['bytes'])} "
            f"| {item['files']} | {item['n']} | {item['wall']:.3f} "
            f"| {item['copy']:.3f} | {item['fsync']:.3f} "
            f"| {item['metric']:.1f} {item['unit']} "
            f"({item['metric_min']:.1f}-{item['metric_max']:.1f}) |"
        )

    lines.extend(["", "## Copier comparison", ""])
    lines.append(
        "| mount | workload | kind | C | fsync | pattern | metric | "
        + " | ".join(copiers)
        + " |"
    )
    lines.append("|---|---|---|---|---|---|---|" + "---|" * len(copiers))
    comparison_keys = sorted(
        {
            (key[0], key[1], key[2], key[3], key[5], key[6], key[7])
            for key in keys
        },
        key=lambda item: (
            mounts.index(item[0]),
            kind_order.get(item[2], 9),
            item[1],
            item[3],
            item[4],
            item[5],
            item[6],
        ),
    )
    for comparison in comparison_keys:
        (
            mount,
            workload,
            kind,
            concurrency,
            fsync,
            cache_state,
            data_pattern,
        ) = comparison
        values: dict[str, float] = {}
        unit = metric_field(kind)[1]
        for copier in copiers:
            key = (
                mount,
                workload,
                kind,
                concurrency,
                copier,
                fsync,
                cache_state,
                data_pattern,
            )
            if key in aggregates:
                values[copier] = aggregates[key]["metric"]
        cells = [
            f"{values[copier]:.1f}" if copier in values else "-"
            for copier in copiers
        ]
        lines.append(
            f"| {mount} | {workload} | {kind} | {concurrency} "
            f"| {'on' if fsync else 'off'} | {data_pattern} | {unit} | "
            + " | ".join(cells)
            + " |"
        )

    if len(mounts) > 1:
        lines.extend(["", "## Mount comparison", ""])
        lines.append(
            "| workload | kind | C | copier | fsync | pattern | metric | "
            + " | ".join(mounts)
            + " |"
        )
        lines.append("|---|---|---|---|---|---|---|" + "---|" * len(mounts))
        mount_keys = sorted(
            {
                (key[1], key[2], key[3], key[4], key[5], key[6], key[7])
                for key in keys
            },
            key=lambda item: (
                kind_order.get(item[1], 9),
                item[0],
                item[2],
                copiers.index(item[3]),
                item[4],
                item[5],
                item[6],
            ),
        )
        for mount_key in mount_keys:
            (
                workload,
                kind,
                concurrency,
                copier,
                fsync,
                cache_state,
                data_pattern,
            ) = mount_key
            values_by_mount: dict[str, float] = {}
            unit = metric_field(kind)[1]
            for mount in mounts:
                key = (
                    mount,
                    workload,
                    kind,
                    concurrency,
                    copier,
                    fsync,
                    cache_state,
                    data_pattern,
                )
                if key in aggregates:
                    values_by_mount[mount] = aggregates[key]["metric"]
            cells = [
                f"{values_by_mount[mount]:.1f}"
                if mount in values_by_mount
                else "-"
                for mount in mounts
            ]
            lines.append(
                f"| {workload} | {kind} | {concurrency} | {copier} "
                f"| {'on' if fsync else 'off'} | {data_pattern} | {unit} | "
                + " | ".join(cells)
                + " |"
            )

    curves: dict[tuple[Any, ...], dict[int, float]] = defaultdict(dict)
    for key, item in aggregates.items():
        (
            mount,
            workload,
            kind,
            concurrency,
            copier,
            fsync,
            cache_state,
            data_pattern,
        ) = key
        curves[(mount, workload, kind, copier, fsync, cache_state, data_pattern)][
            concurrency
        ] = item["metric"]
    curve_keys = [
        key
        for key, values in curves.items()
        if len(values) > 1
    ]
    if curve_keys:
        lines.extend(["", "## Concurrency curves", ""])
        for curve in sorted(
            curve_keys,
            key=lambda item: (
                mounts.index(item[0]),
                kind_order.get(item[2], 9),
                item[1],
                copiers.index(item[3]),
                item[4],
                item[5],
                item[6],
            ),
        ):
            (
                mount,
                workload,
                kind,
                copier,
                fsync,
                _cache_state,
                data_pattern,
            ) = curve
            values = curves[curve]
            levels = sorted(values)
            unit = metric_field(kind)[1]
            peak_level = max(levels, key=lambda level: values[level])
            lines.append(
                f"### {mount} / {workload} / {copier} "
                f"(fsync={'on' if fsync else 'off'}, pattern={data_pattern})"
            )
            lines.append("")
            lines.append(
                "| metric | "
                + " | ".join(f"C={level}" for level in levels)
                + " | peak C |"
            )
            lines.append("|---|" + "---|" * len(levels) + "---|")
            lines.append(
                f"| {unit} | "
                + " | ".join(f"{values[level]:.1f}" for level in levels)
                + f" | C={peak_level} |"
            )
            lines.append("")

    lines.append("")
    lines.extend(
        [
            "## Measurement notes",
            "",
            "- Warm-up reads the source once per case. It is best effort: the "
            "kernel may evict pages, and userspace client caches are not reset.",
            "- `wall_s` includes fsync. For C>1, wall time also includes "
            "`ProcessPoolExecutor` startup; `copy_s` does not.",
            "- Every repeat verifies the destination's relative file set and "
            "file sizes against the source. Contents are not hashed.",
            "- External copiers are timed like built-ins. A metadata-only clone "
            "will therefore show high logical MiB/s without moving data.",
            "",
        ]
    )
    return "\n".join(lines)


def manifest_text(
    args: argparse.Namespace,
    copiers: Sequence[Copier],
    run_dir: Path,
    started_utc: str,
    finished_utc: str,
) -> str:
    fsync_mode = "fsync" if args.fsync else "none"
    external = {
        copier.name: shlex.join(copier.argv)
        for copier in copiers
        if copier.kind == "external"
    }
    lines = [
        f"script={SCRIPT_NAME}",
        f"argv={shlex.join(sys.argv)}",
        f"started_utc={started_utc}",
        f"finished_utc={finished_utc}",
        f"hostname={socket.gethostname()}",
        f"platform={platform.platform()}",
        f"python={sys.version.replace(chr(10), ' ')}",
        f"mount={args.mount}",
        f"fstype={fstype(args.mount)}",
        f"cache_state={CACHE_STATE}",
        "cold_mode=disabled",
        f"fsync_mode={fsync_mode}",
        f"copiers={','.join(copier.name for copier in copiers)}",
        "external_copiers=" + json.dumps(external, sort_keys=True),
        f"threads={args.threads}",
        f"repeats={args.repeats}",
        f"stage={args.stage}",
        f"small_count={args.small_count}",
        f"conc_levels={','.join(str(level) for level in args.conc_levels)}",
        f"data_pattern={args.data_pattern}",
        f"scratch_subpath={args.scratch_subpath}",
        f"keep_scratch={int(args.keep_scratch)}",
        f"append_csv={args.append_csv or '-'}",
        f"results_dir={run_dir}",
    ]
    return "\n".join(lines) + "\n"


def write_run_artifacts(
    args: argparse.Namespace,
    copiers: Sequence[Copier],
    run_dir: Path,
    rows: Sequence[dict[str, Any]],
    started_utc: str,
    finished_utc: str,
) -> None:
    (run_dir / "summary.md").write_text(
        render_report(rows), encoding="utf-8"
    )
    (run_dir / "manifest.txt").write_text(
        manifest_text(
            args, copiers, run_dir, started_utc, finished_utc
        ),
        encoding="utf-8",
    )
    result = {
        "script": SCRIPT_NAME,
        "argv": sys.argv,
        "started_utc": started_utc,
        "finished_utc": finished_utc,
        "mount": args.mount,
        "fstype": fstype(args.mount),
        "cache_state": CACHE_STATE,
        "fsync_mode": "fsync" if args.fsync else "none",
        "copiers": [copier.name for copier in copiers],
        "external_copiers": {
            copier.name: list(copier.argv)
            for copier in copiers
            if copier.kind == "external"
        },
        "threads": args.threads,
        "repeats": args.repeats,
        "stage": args.stage,
        "data_pattern": args.data_pattern,
        "rows": rows,
    }
    (run_dir / "result.json").write_text(
        json.dumps(result, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def run_benchmark(args: argparse.Namespace) -> int:
    mount = os.path.abspath(os.path.expanduser(args.mount))
    if not os.path.isdir(mount):
        raise BenchmarkError(f"--mount must be an existing directory: {mount}")
    args.mount = mount
    scratch_subpath = os.path.normpath(args.scratch_subpath)
    if (
        scratch_subpath in ("", ".")
        or os.path.isabs(scratch_subpath)
        or scratch_subpath.startswith("..")
    ):
        raise BenchmarkError(
            "--scratch-subpath must stay inside --mount and be relative"
        )
    args.scratch_subpath = scratch_subpath

    copiers = resolve_copiers(args)
    cp_binary = args.cp_binary or shutil.which("cp") or ""
    if any(copier.kind in ("cp", "cpr") for copier in copiers):
        if not cp_binary:
            raise BenchmarkError("could not find cp; pass --cp-binary")
        if not os.path.isfile(cp_binary) or not os.access(cp_binary, os.X_OK):
            raise BenchmarkError(f"cp binary is not executable: {cp_binary}")

    plan = dedupe_plan(
        filter_plan(
            build_plan(
                args.stage,
                args.smoke,
                args.small_count,
                args.conc_levels,
            ),
            args.kinds,
        )
    )
    if not plan:
        raise BenchmarkError("no benchmark cases selected")

    run_dir = Path(results_run_dir(SCRIPT_NAME, anchor=__file__))
    started_utc = utc_now()
    rows: list[dict[str, Any]] = []
    log(
        f"=== mount={mount} stage={args.stage} "
        f"copiers={','.join(copier.name for copier in copiers)} "
        f"cache={CACHE_STATE} fsync={args.fsync} repeats={args.repeats} "
        f"cases={len(plan)} ==="
    )
    raw_path = run_dir / "raw.csv"
    with CsvSink(raw_path, args.append_csv) as sink:
        for spec in plan:
            rows.extend(
                run_case(
                    mount,
                    spec,
                    args,
                    sink,
                    run_dir.name,
                    copiers,
                    cp_binary,
                )
            )
    finished_utc = utc_now()
    write_run_artifacts(
        args, copiers, run_dir, rows, started_utc, finished_utc
    )
    log(f"results: {run_dir}")
    log(f"summary: {run_dir / 'summary.md'}")
    return 0


def run_report(args: argparse.Namespace) -> int:
    rows = load_rows(args.raw)
    report = render_report(rows)
    if args.out:
        output = Path(args.out).expanduser()
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(report, encoding="utf-8")
        log(f"report: {output}")
    else:
        print(report)
    return 0


# ------------------------------- command line -------------------------------


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Same-filesystem copy/clone benchmark."
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    run = subparsers.add_parser(
        "run",
        help="generate warm source data and measure copies",
    )
    run.add_argument(
        "--mount",
        required=True,
        help="directory on the filesystem under test",
    )
    run.add_argument(
        "--stage",
        default="single",
        choices=["single", "concurrency", "all"],
        help="default: single",
    )
    run.add_argument(
        "--repeats",
        type=positive_int,
        default=3,
        help="repetitions per case; all are warm (default: 3)",
    )
    run.add_argument(
        "--copier",
        action="append",
        default=[],
        help="copier name; repeatable (cp, cpr, internal, or an external name)",
    )
    run.add_argument(
        "--copiers",
        default="",
        help="comma list of copier names; combined with repeated --copier",
    )
    run.add_argument(
        "--external-copier",
        action="append",
        default=[],
        metavar="NAME=COMMAND",
        help=(
            "external copier command with {src} and {dst} placeholders; "
            "{threads} is optional"
        ),
    )
    run.add_argument(
        "--threads",
        type=positive_int,
        default=1,
        help="value substituted for {threads} in external commands (default: 1)",
    )
    run.add_argument(
        "--cp-binary",
        default="",
        help="path to cp (default: resolve cp on PATH)",
    )
    run.add_argument(
        "--fsync",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="fsync copied files and directories (default: on)",
    )
    run.add_argument(
        "--conc-levels",
        type=comma_ints,
        default=(1, 4, 16),
        help="concurrency levels for --stage concurrency (default: 1,4,16)",
    )
    run.add_argument(
        "--small-count",
        type=positive_int,
        default=10000,
        help="small files per small-file workload (default: 10000)",
    )
    run.add_argument(
        "--data-pattern",
        choices=["random", "zeros"],
        default="random",
        help=(
            "source contents; random avoids compression/dedup effects "
            "(default: random)"
        ),
    )
    run.add_argument(
        "--kinds",
        default="",
        help="comma list to filter workloads: large,small",
    )
    run.add_argument(
        "--smoke",
        action="store_true",
        help="run four small cases instead of the selected stage",
    )
    run.add_argument(
        "--scratch-subpath",
        default="clone-bench/scratch",
        help="scratch directory relative to --mount",
    )
    run.add_argument(
        "--append-csv",
        default="",
        help="also append rows to this CSV (creates/validates the header)",
    )
    run.add_argument(
        "--keep-scratch",
        action="store_true",
        help="keep source and destination trees for inspection",
    )
    run.set_defaults(func=run_benchmark)

    report = subparsers.add_parser(
        "report",
        help="aggregate one raw.csv and print or write a report",
    )
    report.add_argument("--raw", required=True, help="raw.csv to aggregate")
    report.add_argument(
        "--out",
        default="",
        help="write Markdown here instead of printing it",
    )
    report.set_defaults(func=run_report)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    arguments = list(sys.argv[1:] if argv is None else argv)
    parser = build_parser()
    if not arguments:
        parser.print_help()
        return 0
    if arguments[0] not in ("run", "report"):
        # Keep `clone_bench.py --mount ...` working like the other scripts.
        arguments.insert(0, "run")
    args = parser.parse_args(arguments)
    try:
        return args.func(args)
    except BenchmarkError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
