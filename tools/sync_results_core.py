#!/usr/bin/env python3
"""Inline ``tools/results_core.py`` into every benchmark script.

Each benchmark script must stay runnable on its own, so the shared helper is
embedded between generated-block markers instead of imported. This tool keeps
those copies in sync.

    uv run tools/sync_results_core.py          # rewrite stale copies
    uv run tools/sync_results_core.py --check  # fail if any copy is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
SOURCE = SCRIPT_DIR / "results_core.py"
SOURCE_REL = "tools/results_core.py"

BEGIN = "# >>> BEGIN GENERATED results-core (source: tools/results_core.py) >>>"
END = "# <<< END GENERATED results-core <<<"

TARGETS = (
    REPO_ROOT / "dev_workflow_fs.py",
    REPO_ROOT / "mini_dev_workflow_fs.py",
    REPO_ROOT / "npm_install_fs_bench.py",
    REPO_ROOT / "openclaw_session_bench.py",
)


def generated_block() -> str:
    """Return the helper body with its module docstring removed."""
    body = SOURCE.read_text(encoding="utf-8")
    if body.startswith('"""'):
        end = body.find('"""', 3)
        if end == -1:
            raise SystemExit(f"{SOURCE}: unterminated module docstring")
        body = body[end + 3 :]
    body = body.strip("\n")
    note = (
        "# Generated by tools/sync_results_core.py from\n"
        "# tools/results_core.py -- edit that file, then re-run the tool.\n"
    )
    return f"{BEGIN}\n{note}\n{body}\n{END}\n"


def replace_block(path: Path, block: str) -> str:
    text = path.read_text(encoding="utf-8")
    start = text.find(BEGIN)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        raise SystemExit(f"{path}: generated results-core markers not found")
    end += len(END)
    while end < len(text) and text[end] == "\n":
        end += 1
    return f"{text[:start]}{block}\n{text[end:]}"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the embedded copies are current without writing",
    )
    args = parser.parse_args(argv)

    block = generated_block()
    stale: list[Path] = []
    for target in TARGETS:
        if not target.exists():
            raise SystemExit(f"{target}: missing benchmark script")
        updated = replace_block(target, block)
        if updated == target.read_text(encoding="utf-8"):
            continue
        stale.append(target)
        if not args.check:
            target.write_text(updated, encoding="utf-8")

    if not stale:
        print(f"results-core ({SOURCE_REL}): all embedded copies are current")
        return 0

    verb = "stale" if args.check else "updated"
    for target in stale:
        print(f"results-core: {verb}: {target}")
    if args.check:
        print("run: uv run tools/sync_results_core.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
