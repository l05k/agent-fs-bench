def _mount_host(plan: ExperimentPlan, host: Host) -> dict[str, Any]:
    nas = plan.nas
    mountpoint = shlex.quote(nas.mountpoint)
    expected_source = shlex.quote(nas.source)
    source_check = "1" if nas.verify_source else "0"
    mount_argv = [nas.mount_bin]
    if nas.fstype:
        mount_argv.extend(["-t", nas.fstype])
    if nas.options:
        mount_argv.extend(["-o", nas.options])
    mount_argv.extend([nas.source, nas.mountpoint])
    mount_line = _privilege_prefix(plan) + _remote_command(mount_argv)
    lines = [
        "set -eu",
        f"mountpoint={mountpoint}",
        f"expected_source={expected_source}",
        f"verify_source={source_check}",
        'if mountpoint -q "$mountpoint"; then',
        "  state=already",
        '  current_source=$(findmnt -n -o SOURCE --target "$mountpoint" | head -n 1)',
        '  if [ "$verify_source" = "1" ]; then',
        '    current_normalized=${current_source%/}',
        '    expected_normalized=${expected_source%/}',
        '    if [ "$current_normalized" != "$expected_normalized" ]; then',
        '      printf "CURRENT_SOURCE=%s\\n" "$current_source"',
        '      printf "EXPECTED_SOURCE=%s\\n" "$expected_source"',
        "      exit 42",
        "    fi",
        "  fi",
        "else",
        '  mkdir -p "$mountpoint"',
        f"  {mount_line}",
        "  state=mounted",
        "fi",
        'printf "STATE=%s\\n" "$state"',
        'printf "SOURCE=%s\\n" "$(findmnt -n -o SOURCE --target "$mountpoint" | head -n 1)"',
        'printf "FSTYPE=%s\\n" "$(findmnt -n -o FSTYPE --target "$mountpoint" | head -n 1)"',
        'printf "OPTIONS=%s\\n" "$(findmnt -n -o OPTIONS --target "$mountpoint" | head -n 1)"',
        'df -P "$mountpoint" | tail -n 1',
    ]
    completed = _ssh_call(
        plan,
        host,
        "\n".join(lines),
        timeout_s=nas.mount_timeout_s,
    )
    parsed: dict[str, Any] = {
        "state": "",
        "source": "",
        "fstype": "",
        "options": "",
        "df": "",
        "stdout": completed.stdout,
        "stderr": completed.stderr,
        "exit_code": completed.returncode,
        "owned": False,
    }
    for line in (completed.stdout or "").splitlines():
        if "=" in line:
            key, value = line.split("=", 1)
            if key in ("STATE", "SOURCE", "FSTYPE", "OPTIONS"):
                parsed[key.lower()] = value
        elif line.strip():
            parsed["df"] = line.strip()
    if parsed["state"] == "mounted":
        parsed["owned"] = True
    if completed.returncode != 0:
        cleanup_note = ""
        if parsed["owned"]:
            try:
                _unmount_host(plan, host)
                cleanup_note = "; the mount was unmounted after verification failed"
            except Exception as cleanup_exc:
                cleanup_note = f"; cleanup unmount also failed: {cleanup_exc}"
        raise RemoteError(
            f"{host.name}: mount failed with exit {completed.returncode}: "
            f"{_ssh_output(completed)}{cleanup_note}"
        )
    if (
        parsed["owned"]
        and nas.verify_source
        and parsed["source"].rstrip("/") != nas.source.rstrip("/")
    ):
        cleanup_note = ""
        try:
            _unmount_host(plan, host)
            cleanup_note = "; the mismatched mount was unmounted"
        except Exception as cleanup_exc:
            cleanup_note = f"; cleanup unmount also failed: {cleanup_exc}"
        raise RemoteError(
            f"{host.name}: mounted source {parsed['source']!r} does not match "
            f"nas.source {nas.source!r}{cleanup_note}"
        )
    if parsed["state"] not in ("mounted", "already"):
        raise RemoteError(f"{host.name}: mount state is unknown")
    return parsed


def _initialize_run_root(
    plan: ExperimentPlan, host: Host, run_id: str
) -> str:
    run_root = f"{plan.nas.run_root.rstrip('/')}/{run_id}"
    quotes = shlex.quote(run_root)
    probe = shlex.quote(f"{run_root}/.write-probe-{os.getpid()}")
    script = "\n".join(
        [
            "set -eu",
            f"mkdir -p {quotes}/_control {quotes}/_results {quotes}/hosts {quotes}/shared",
            f"printf 'multi-host-nas-fs\\n' > {probe}",
            f"rm -f {probe}",
            f"printf 'run_id={run_id}\\n' > {quotes}/_control/owner",
        ]
    )
    _ssh_checked(plan, host, script, timeout_s=plan.ssh.command_timeout_s)
    return run_root


def _unmount_host(plan: ExperimentPlan, host: Host) -> dict[str, Any]:
    mountpoint = shlex.quote(plan.nas.mountpoint)
    unmount_argv = [plan.nas.umount_bin]
    if plan.nas.lazy_unmount:
        unmount_argv.append("-l")
    unmount_argv.append(plan.nas.mountpoint)
    unmount_line = _privilege_prefix(plan) + _remote_command(unmount_argv)
    script = "\n".join(
        [
            "set -eu",
            f"mountpoint={mountpoint}",
            'if mountpoint -q "$mountpoint"; then',
            f"  {unmount_line}",
            "  state=unmounted",
            "else",
            "  state=not-mounted",
            "fi",
            'printf "STATE=%s\\n" "$state"',
        ]
    )
    completed = _ssh_call(
        plan,
        host,
        script,
        timeout_s=plan.nas.unmount_timeout_s,
    )
    state = ""
    for line in (completed.stdout or "").splitlines():
        if line.startswith("STATE="):
            state = line.split("=", 1)[1]
    if completed.returncode != 0:
        raise RemoteError(
            f"{host.name}: unmount failed with exit {completed.returncode}: "
            f"{_ssh_output(completed)}"
        )
    return {
        "state": state,
        "stdout": completed.stdout,
        "stderr": completed.stderr,
        "exit_code": completed.returncode,
    }


