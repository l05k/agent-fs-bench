def _strip_yaml_comment(line: str) -> str:
    """Remove a YAML comment while respecting single and double quotes."""
    quote: str | None = None
    escaped = False
    index = 0
    while index < len(line):
        char = line[index]
        if quote == '"':
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                quote = None
            index += 1
            continue
        if quote == "'":
            if char == "'":
                if index + 1 < len(line) and line[index + 1] == "'":
                    index += 2
                    continue
                quote = None
            index += 1
            continue
        if char in ("'", '"'):
            quote = char
        elif char == "#" and (index == 0 or line[index - 1].isspace()):
            return line[:index]
        index += 1
    return line


def _split_mapping_entry(text: str, line_number: int) -> tuple[str, str]:
    """Split ``key: value`` on the first unquoted colon."""
    quote: str | None = None
    escaped = False
    index = 0
    while index < len(text):
        char = text[index]
        if quote == '"':
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                quote = None
            index += 1
            continue
        if quote == "'":
            if char == "'":
                if index + 1 < len(text) and text[index + 1] == "'":
                    index += 2
                    continue
                quote = None
            index += 1
            continue
        if char in ("'", '"'):
            quote = char
            index += 1
            continue
        if char == ":" and (
            index + 1 == len(text) or text[index + 1].isspace()
        ):
            key = text[:index].strip()
            if not key:
                raise PlanError(f"line {line_number}: empty mapping key")
            if key[0] in "{[":
                raise PlanError(
                    f"line {line_number}: flow mappings/sequences are not supported"
                )
            return key, text[index + 1 :].strip()
        index += 1
    raise PlanError(f"line {line_number}: expected 'key: value'")


def _parse_yaml_scalar(text: str, line_number: int) -> Any:
    value = text.strip()
    if not value:
        return None
    if value in ("null", "Null", "NULL", "~"):
        return None
    if value in ("true", "True", "TRUE"):
        return True
    if value in ("false", "False", "FALSE"):
        return False
    if value.startswith(("&", "*", "!", "|", ">", "[", "{")):
        raise PlanError(
            f"line {line_number}: unsupported YAML construct {value!r}"
        )
    if value.startswith('"'):
        if not value.endswith('"') or len(value) < 2:
            raise PlanError(f"line {line_number}: unterminated double quote")
        try:
            return json.loads(value)
        except json.JSONDecodeError as exc:
            raise PlanError(
                f"line {line_number}: invalid double-quoted scalar: {exc}"
            ) from exc
    if value.startswith("'"):
        if not value.endswith("'") or len(value) < 2:
            raise PlanError(f"line {line_number}: unterminated single quote")
        return value[1:-1].replace("''", "'")
    normalized = value.replace("_", "")
    if re.fullmatch(r"[-+]?(?:0|[1-9][0-9]*)", normalized):
        try:
            return int(normalized)
        except ValueError:
            pass
    if re.fullmatch(
        r"[-+]?(?:[0-9]+\.[0-9]*|\.[0-9]+)(?:[eE][-+]?[0-9]+)?",
        normalized,
    ):
        try:
            return float(normalized)
        except ValueError:
            pass
    return value


def _parse_yaml_block(
    lines: Sequence[_YamlLine], index: int, indent: int
) -> tuple[Any, int]:
    if index >= len(lines) or lines[index].indent != indent:
        raise PlanError("invalid YAML indentation")
    starts_sequence = lines[index].text == "-" or lines[index].text.startswith(
        "- "
    )
    if starts_sequence:
        return _parse_yaml_sequence(lines, index, indent)
    return _parse_yaml_mapping(lines, index, indent)


def _parse_yaml_mapping(
    lines: Sequence[_YamlLine], index: int, indent: int
) -> tuple[dict[str, Any], int]:
    result: dict[str, Any] = {}
    while index < len(lines):
        line = lines[index]
        if line.indent < indent:
            break
        if line.indent > indent:
            raise PlanError(
                f"line {line.number}: unexpected indentation"
            )
        if line.text == "-" or line.text.startswith("- "):
            raise PlanError(
                f"line {line.number}: sequence item inside a mapping"
            )
        key, raw_value = _split_mapping_entry(line.text, line.number)
        if key in result:
            raise PlanError(f"line {line.number}: duplicate key {key!r}")
        index += 1
        if raw_value:
            result[key] = _parse_yaml_scalar(raw_value, line.number)
            if index < len(lines) and lines[index].indent > indent:
                raise PlanError(
                    f"line {lines[index].number}: nested value after inline scalar"
                )
            continue
        if index < len(lines) and lines[index].indent > indent:
            result[key], index = _parse_yaml_block(
                lines, index, lines[index].indent
            )
        else:
            result[key] = None
    return result, index


def _parse_yaml_sequence(
    lines: Sequence[_YamlLine], index: int, indent: int
) -> tuple[list[Any], int]:
    result: list[Any] = []
    while index < len(lines):
        line = lines[index]
        if line.indent < indent:
            break
        if line.indent > indent:
            raise PlanError(
                f"line {line.number}: unexpected indentation in sequence"
            )
        if line.text != "-" and not line.text.startswith("- "):
            break
        content = line.text[1:].strip()
        index += 1
        if not content:
            if index < len(lines) and lines[index].indent > indent:
                item, index = _parse_yaml_block(
                    lines, index, lines[index].indent
                )
                result.append(item)
            else:
                result.append(None)
            continue
        try:
            first_key, first_value = _split_mapping_entry(
                content, line.number
            )
        except PlanError:
            result.append(_parse_yaml_scalar(content, line.number))
            if index < len(lines) and lines[index].indent > indent:
                raise PlanError(
                    f"line {lines[index].number}: nested value after sequence scalar"
                )
            continue
        item: dict[str, Any] = {}
        if first_value:
            item[first_key] = _parse_yaml_scalar(first_value, line.number)
        elif index < len(lines) and lines[index].indent > indent:
            item[first_key], index = _parse_yaml_block(
                lines, index, lines[index].indent
            )
        else:
            item[first_key] = None
        if index < len(lines) and lines[index].indent > indent:
            continuation_indent = lines[index].indent
            continuation, index = _parse_yaml_block(
                lines, index, continuation_indent
            )
            if not isinstance(continuation, dict):
                raise PlanError(
                    f"line {lines[index - 1].number}: expected mapping continuation"
                )
            overlap = set(item).intersection(continuation)
            if overlap:
                raise PlanError(
                    f"line {lines[index - 1].number}: duplicate key "
                    f"{sorted(overlap)[0]!r}"
                )
            item.update(continuation)
        result.append(item)
    return result, index


def parse_yaml(text: str) -> Any:
    """Parse the strict YAML subset used by the experiment plan."""
    lines: list[_YamlLine] = []
    for number, raw_line in enumerate(text.splitlines(), 1):
        if "\t" in raw_line:
            raise PlanError(f"line {number}: tabs are not allowed")
        without_comment = _strip_yaml_comment(raw_line).rstrip()
        if not without_comment.strip():
            continue
        stripped = without_comment.lstrip(" ")
        if stripped in ("---", "..."):
            if lines:
                raise PlanError(
                    f"line {number}: multi-document YAML is not supported"
                )
            continue
        indent = len(without_comment) - len(stripped)
        lines.append(_YamlLine(indent, stripped, number))
    if not lines:
        raise PlanError("empty YAML document")
    value, index = _parse_yaml_block(lines, 0, lines[0].indent)
    if index != len(lines):
        raise PlanError(f"line {lines[index].number}: trailing content")
    return value


def _mapping(value: Any, path: str) -> dict[str, Any]:
    if value is None:
        return {}
    if not isinstance(value, dict):
        raise PlanError(f"{path}: expected a mapping")
    return value


def _sequence(value: Any, path: str) -> list[Any]:
    if value is None:
        return []
    if not isinstance(value, list):
        raise PlanError(f"{path}: expected a list")
    return value


def _check_keys(
    value: dict[str, Any], path: str, allowed: set[str]
) -> None:
    unknown = set(value).difference(allowed)
    if unknown:
        raise PlanError(
            f"{path}: unknown key(s): {', '.join(sorted(unknown))}"
        )


def _text(
    value: Any,
    path: str,
    *,
    required: bool = False,
    default: str = "",
) -> str:
    if value is None:
        if required:
            raise PlanError(f"{path}: is required")
        return default
    if not isinstance(value, str) or not value.strip():
        raise PlanError(f"{path}: expected a non-empty string")
    return value.strip()


def _positive_int(
    value: Any, path: str, *, default: int | None = None
) -> int:
    if value is None:
        if default is None:
            raise PlanError(f"{path}: is required")
        return default
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise PlanError(f"{path}: expected an integer greater than zero")
    return value


def _bool(value: Any, path: str, *, default: bool) -> bool:
    if value is None:
        return default
    if not isinstance(value, bool):
        raise PlanError(f"{path}: expected true or false")
    return value


def _absolute_remote_path(value: str, path: str) -> str:
    if not value.startswith("/"):
        raise PlanError(f"{path}: must be an absolute remote path")
    if any(part in (".", "..") for part in PurePosixPath(value).parts):
        raise PlanError(f"{path}: '.' and '..' path segments are not allowed")
    return value.rstrip("/") or "/"


