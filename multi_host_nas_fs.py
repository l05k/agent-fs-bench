def _write_json_atomic(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    temporary.write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    os.replace(temporary, path)


def _worker_log(message: str) -> None:
    print(f"[worker] {message}", file=sys.stderr, flush=True)


def _run_worker_job(job: dict[str, Any]) -> dict[str, Any]:
    host_name = str(job["host_name"])
    run_root = Path(str(job["run_root"]))
    host_dir = Path(str(job["host_dir"]))
    shared_dir = Path(str(job["shared_dir"]))
    result_path = Path(str(job["result_path"]))
    workload = WorkloadConfig(
        files_per_host=int(job["workload"]["files_per_host"]),
        file_size_bytes=int(job["workload"]["file_size_bytes"]),
        directories=int(job["workload"]["directories"]),
        shared_files_per_host=int(job["workload"]["shared_files_per_host"]),
        rounds=int(job["workload"]["rounds"]),
        fsync=bool(job["workload"]["fsync"]),
        read_back=bool(job["workload"]["read_back"]),
        cleanup_private=bool(job["workload"]["cleanup_private"]),
    )
    if host_dir.exists():
        raise WorkerError(f"host directory already exists: {host_dir}")
    host_dir.mkdir(parents=True)
    shared_dir.mkdir(parents=True, exist_ok=True)
    payload = _payload(host_name, workload.file_size_bytes)
    started_at_ns = time.time_ns()
    started_at_utc = datetime.now(timezone.utc).strftime(
        "%Y-%m-%dT%H:%M:%SZ"
    )
    metrics: list[dict[str, Any]] = []
    for round_number in range(1, workload.rounds + 1):
        _worker_log(f"round {round_number}/{workload.rounds}: private")
        private_metrics, _renamed = _run_private_round(
            round_number,
            host_dir,
            workload,
            payload,
        )
        metrics.extend(private_metrics)
        _worker_log(f"round {round_number}/{workload.rounds}: shared")
        metrics.extend(
            _run_shared_round(
                round_number,
                shared_dir,
                host_name,
                workload,
                payload,
            )
        )
    _worker_log("workload complete")
    finished_at_ns = time.time_ns()
    if workload.cleanup_private:
        shutil.rmtree(host_dir, ignore_errors=True)
    result = {
        "schema_version": SCHEMA_VERSION,
        "success": True,
        "host_name": host_name,
        "hostname": socket.gethostname(),
        "platform": platform.platform(),
        "kernel": platform.release(),
        "python": platform.python_version(),
        "pid": os.getpid(),
        "started_at_utc": started_at_utc,
        "started_at_ns": started_at_ns,
        "finished_at_ns": finished_at_ns,
        "elapsed_s": (finished_at_ns - started_at_ns) / 1_000_000_000,
        "run_root": str(run_root),
        "host_dir": str(host_dir),
        "shared_dir": str(shared_dir),
        "cleanup_private": workload.cleanup_private,
        "metrics": metrics,
    }
    return result


def _worker_error_result(
    job: dict[str, Any] | None,
    exc: BaseException,
) -> dict[str, Any]:
    return {
        "schema_version": SCHEMA_VERSION,
        "success": False,
        "host_name": str(job.get("host_name", "unknown")) if job else "unknown",
        "error": str(exc),
        "error_type": type(exc).__name__,
        "traceback": traceback.format_exc(),
    }


def _wait_for_go(timeout_s: int) -> float:
    gate_started = time.perf_counter()

    def timeout_handler(_signum: int, _frame: Any) -> None:
        raise GateTimeout(
            f"start gate was not released within {timeout_s} seconds"
        )

    previous = signal.signal(signal.SIGALRM, timeout_handler)
    signal.setitimer(signal.ITIMER_REAL, timeout_s)
    try:
        line = sys.stdin.readline()
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        signal.signal(signal.SIGALRM, previous)
    if line.strip() != "GO":
        raise GateTimeout("start gate closed before GO was received")
    return time.perf_counter() - gate_started


def worker_main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Internal remote worker for multi_host_nas_fs.py"
    )
    parser.add_argument("--job", required=True, help="Path to the JSON job")
    args = parser.parse_args(argv)
    job: dict[str, Any] | None = None

    def interrupt_handler(_signum: int, _frame: Any) -> None:
        raise WorkerError("worker interrupted")

    signal.signal(signal.SIGTERM, interrupt_handler)
    signal.signal(signal.SIGINT, interrupt_handler)

    try:
        job = json.loads(Path(args.job).read_text(encoding="utf-8"))
        if job.get("schema_version") != SCHEMA_VERSION:
            raise WorkerError("unsupported worker job schema")
        print("READY", flush=True)
        gate_wait_s = _wait_for_go(int(job["ready_timeout_s"]))
        run_timeout_s = int(job["run_timeout_s"])

        def run_timeout_handler(_signum: int, _frame: Any) -> None:
            raise WorkerError(
                f"workload exceeded run_timeout_s={run_timeout_s}"
            )

        previous = signal.signal(signal.SIGALRM, run_timeout_handler)
        signal.setitimer(signal.ITIMER_REAL, run_timeout_s)
        try:
            result = _run_worker_job(job)
        finally:
            signal.setitimer(signal.ITIMER_REAL, 0)
            signal.signal(signal.SIGALRM, previous)
        result["gate_wait_s"] = gate_wait_s
    except BaseException as exc:
        if (
            job is not None
            and "host_dir" in job
            and job.get("workload", {}).get("cleanup_private")
        ):
            shutil.rmtree(Path(str(job["host_dir"])), ignore_errors=True)
        result = _worker_error_result(job, exc)
        print(
            f"worker failed: {type(exc).__name__}: {exc}",
            file=sys.stderr,
            flush=True,
        )
    if job is not None:
        try:
            result_path = Path(str(job["result_path"]))
            _write_json_atomic(result_path, result)
        except OSError as exc:
            print(f"cannot write remote result: {exc}", file=sys.stderr, flush=True)
    print(
        "RESULT_JSON " + json.dumps(result, separators=(",", ":")),
        flush=True,
    )
    return 0 if result.get("success") else 1


def _ssh_destination(host: Host) -> str:
    if host.user:
        return f"{host.user}@{host.address}"
    return host.address


def _ssh_argv(plan: ExperimentPlan, host: Host) -> list[str]:
    argv = [
        "ssh",
        "-T",
        "-o",
        "BatchMode=yes",
        "-o",
        f"ConnectTimeout={plan.ssh.connect_timeout_s}",
        "-o",
        "LogLevel=ERROR",
    ]
    if plan.ssh.identity_file:
        argv.extend(["-i", plan.ssh.identity_file])
    for option in (*plan.ssh.options, *host.options):
        argv.extend(["-o", option])
    argv.extend(["-p", str(host.port), "--", _ssh_destination(host)])
    return argv


def _ssh_call(
    plan: ExperimentPlan,
    host: Host,
    remote_command: str,
    *,
    timeout_s: int | None = None,
    input_data: str | None = None,
) -> subprocess.CompletedProcess[str]:
    argv = _ssh_argv(plan, host)
    argv.append(remote_command)
    try:
        return subprocess.run(
            argv,
            input=input_data,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout_s or plan.ssh.command_timeout_s,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise RemoteError(
            f"{host.name}: SSH command timed out after {timeout_s or plan.ssh.command_timeout_s}s"
        ) from exc
    except OSError as exc:
        raise RemoteError(f"{host.name}: cannot run ssh: {exc}") from exc


def _ssh_output(completed: subprocess.CompletedProcess[str]) -> str:
    output = (completed.stdout or "").strip()
    error = (completed.stderr or "").strip()
    if output and error:
        return f"{output}\n{error}"
    return output or error


def _ssh_checked(
    plan: ExperimentPlan,
    host: Host,
    remote_command: str,
    *,
    timeout_s: int | None = None,
    input_data: str | None = None,
) -> str:
    completed = _ssh_call(
        plan,
        host,
        remote_command,
        timeout_s=timeout_s,
        input_data=input_data,
    )
    if completed.returncode != 0:
        raise RemoteError(
            f"{host.name}: remote command failed with exit "
            f"{completed.returncode}: {_ssh_output(completed)}"
        )
    return (completed.stdout or "").strip()


def _remote_command(argv: Sequence[str]) -> str:
    return shlex.join(list(argv))


def _preflight_host(plan: ExperimentPlan, host: Host) -> dict[str, Any]:
    python_quoted = shlex.quote(plan.remote.python)
    checks = [
        f"if [ -x {python_quoted} ]; then :; else command -v {python_quoted} >/dev/null; fi",
        "command -v mountpoint >/dev/null",
        "command -v findmnt >/dev/null",
        "command -v df >/dev/null",
    ]
    for binary in (plan.nas.mount_bin, plan.nas.umount_bin):
        quoted = shlex.quote(binary)
        checks.append(
            f"if [ -x {quoted} ]; then :; else command -v {quoted} >/dev/null; fi"
        )
    if plan.nas.privileged:
        checks.append("sudo -n true")
    python_probe = (
        "import json,os,platform,sys;"
        "print(json.dumps({"
        "'hostname': platform.node(),"
        "'platform': platform.platform(),"
        "'kernel': platform.release(),"
        "'system': platform.system(),"
        "'uid': os.geteuid(),"
        "'python': platform.python_version(),"
        "'python_executable': sys.executable"
        "}))"
    )
    checks.append(
        _remote_command(
            [
                plan.remote.python,
                "-c",
                python_probe,
            ]
        )
    )
    script = "set -eu\n" + "\n".join(checks)
    output = _ssh_checked(plan, host, script)
    lines = [line for line in output.splitlines() if line.strip()]
    if not lines:
        raise RemoteError(f"{host.name}: preflight produced no Python probe")
    try:
        info = json.loads(lines[-1])
    except json.JSONDecodeError as exc:
        raise RemoteError(
            f"{host.name}: invalid preflight probe: {lines[-1]!r}"
        ) from exc
    if info.get("system") != "Linux":
        raise RemoteError(
            f"{host.name}: this experiment requires Linux (found "
            f"{info.get('system')!r})"
        )
    minor = tuple(
        int(part)
        for part in str(info.get("python", "0.0")).split(".")[:2]
        if part.isdigit()
    )
    if len(minor) < 2 or minor < (3, 9):
        raise RemoteError(
            f"{host.name}: Python 3.9+ is required (found {info.get('python')})"
        )
    if not str(info.get("python_executable", "")).startswith("/"):
        raise RemoteError(f"{host.name}: remote Python path is not absolute")
    info.update(
        {
            "name": host.name,
            "address": host.address,
            "user": host.user,
            "port": host.port,
            "python": plan.remote.python,
            "sudo": plan.nas.privileged,
        }
    )
    return info


def _run_parallel(
    plan: ExperimentPlan,
    label: str,
    function: Any,
    hosts: Sequence[Host] | None = None,
) -> tuple[dict[str, Any], dict[str, str]]:
    results: dict[str, Any] = {}
    errors: dict[str, str] = {}
    selected = tuple(hosts if hosts is not None else plan.hosts)

    def invoke(host: Host) -> tuple[str, Any]:
        return host.name, function(plan, host)

    if not selected:
        return results, errors
    with ThreadPoolExecutor(max_workers=len(selected)) as executor:
        futures = {
            executor.submit(invoke, host): host for host in selected
        }
        for future in as_completed(futures):
            host = futures[future]
            try:
                name, value = future.result()
                results[name] = value
                log(f"{label}: {name} ok")
            except Exception as exc:
                errors[host.name] = str(exc)
                log(f"{label}: {name} failed: {exc}")
    return results, errors


