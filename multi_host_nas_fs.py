@dataclass
class WorkerSession:
    host: Host
    process: subprocess.Popen[str]
    stdout_lines: list[str] = field(default_factory=list)
    stderr_lines: list[str] = field(default_factory=list)
    ready_event: threading.Event = field(default_factory=threading.Event)
    done_event: threading.Event = field(default_factory=threading.Event)
    result: dict[str, Any] | None = None
    protocol_error: str | None = None
    exit_code: int | None = None
    stdout_thread: threading.Thread | None = None
    stderr_thread: threading.Thread | None = None

    def stdout(self) -> str:
        return "".join(self.stdout_lines)

    def stderr(self) -> str:
        return "".join(self.stderr_lines)

    def terminate(self) -> None:
        try:
            if self.process.stdin and not self.process.stdin.closed:
                self.process.stdin.close()
        except OSError:
            pass
        if self.process.poll() is None:
            try:
                self.process.terminate()
            except OSError:
                pass


def _start_worker_session(
    plan: ExperimentPlan,
    host: Host,
    deployment: dict[str, str],
) -> WorkerSession:
    remote_argv = [
        plan.remote.python,
        "-u",
        deployment["worker_path"],
        "worker",
        "--job",
        deployment["job_path"],
    ]
    argv = _ssh_argv(plan, host)
    argv.append(_remote_command(remote_argv))
    try:
        process = subprocess.Popen(
            argv,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="replace",
            bufsize=1,
        )
    except OSError as exc:
        raise RemoteError(f"{host.name}: cannot start ssh worker: {exc}") from exc
    session = WorkerSession(host=host, process=process)

    def read_stdout() -> None:
        assert process.stdout is not None
        for line in process.stdout:
            session.stdout_lines.append(line)
            stripped = line.strip()
            if stripped == "READY":
                session.ready_event.set()
            elif stripped.startswith("RESULT_JSON "):
                raw = stripped[len("RESULT_JSON ") :]
                try:
                    parsed = json.loads(raw)
                except json.JSONDecodeError as exc:
                    session.protocol_error = f"invalid RESULT_JSON: {exc}"
                    continue
                if not isinstance(parsed, dict):
                    session.protocol_error = "RESULT_JSON is not an object"
                    continue
                session.result = parsed
        session.done_event.set()

    def read_stderr() -> None:
        assert process.stderr is not None
        for line in process.stderr:
            session.stderr_lines.append(line)

    session.stdout_thread = threading.Thread(
        target=read_stdout, daemon=True
    )
    session.stderr_thread = threading.Thread(
        target=read_stderr, daemon=True
    )
    session.stdout_thread.start()
    session.stderr_thread.start()
    return session


def _wait_for_ready(
    sessions: Sequence[WorkerSession], timeout_s: int
) -> None:
    deadline = time.monotonic() + timeout_s
    while True:
        if all(session.ready_event.is_set() for session in sessions):
            return
        failed = [
            session
            for session in sessions
            if session.done_event.is_set() and not session.ready_event.is_set()
        ]
        if failed:
            details = "; ".join(
                f"{session.host.name}: {(session.stderr().strip() or session.stdout().strip() or 'exited before READY')}"
                for session in failed
            )
            raise RemoteError(f"worker failed before start gate: {details}")
        if time.monotonic() >= deadline:
            waiting = [
                session.host.name
                for session in sessions
                if not session.ready_event.is_set()
            ]
            raise RemoteError(
                f"workers did not reach the start gate within {timeout_s}s: "
                f"{', '.join(waiting)}"
            )
        time.sleep(0.02)


def _release_start_gate(sessions: Sequence[WorkerSession]) -> tuple[int, int]:
    started = time.time_ns()
    for session in sessions:
        if session.process.stdin is None:
            raise RemoteError(f"{session.host.name}: worker stdin is unavailable")
        try:
            session.process.stdin.write("GO\n")
            session.process.stdin.flush()
        except (BrokenPipeError, OSError) as exc:
            raise RemoteError(
                f"{session.host.name}: cannot release start gate: {exc}"
            ) from exc
    finished = time.time_ns()
    for session in sessions:
        if session.process.stdin and not session.process.stdin.closed:
            try:
                session.process.stdin.close()
            except OSError:
                pass
    return started, finished


def _wait_for_workers(
    sessions: Sequence[WorkerSession], timeout_s: int
) -> None:
    deadline = time.monotonic() + timeout_s
    while not all(session.done_event.is_set() for session in sessions):
        if time.monotonic() >= deadline:
            pending = [
                session.host.name
                for session in sessions
                if not session.done_event.is_set()
            ]
            for session in sessions:
                session.terminate()
            raise RemoteError(
                f"workers did not finish within {timeout_s}s: "
                f"{', '.join(pending)}"
            )
        time.sleep(0.05)
    for session in sessions:
        try:
            session.exit_code = session.process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            session.terminate()
            raise RemoteError(
                f"{session.host.name}: ssh process did not exit after worker output"
            )
    for session in sessions:
        for thread in (session.stdout_thread, session.stderr_thread):
            if thread is not None:
                thread.join(timeout=2)


def _abort_sessions(sessions: Iterable[WorkerSession]) -> None:
    for session in sessions:
        session.terminate()
    for session in sessions:
        try:
            session.process.wait(timeout=5)
        except (subprocess.TimeoutExpired, OSError):
            try:
                session.process.kill()
            except OSError:
                pass


def _run_workers(
    plan: ExperimentPlan,
    deployments: dict[str, dict[str, str]],
) -> tuple[dict[str, WorkerSession], dict[str, str], float]:
    sessions: dict[str, WorkerSession] = {}
    errors: dict[str, str] = {}
    gate_control_write_ms = 0.0
    for host in plan.hosts:
        try:
            sessions[host.name] = _start_worker_session(
                plan, host, deployments[host.name]
            )
        except Exception as exc:
            errors[host.name] = str(exc)
    if errors:
        _abort_sessions(sessions.values())
        return sessions, errors, gate_control_write_ms
    try:
        _wait_for_ready(tuple(sessions.values()), plan.remote.ready_timeout_s)
        log(f"start gate: all {len(sessions)} workers ready")
        gate_started, gate_finished = _release_start_gate(
            tuple(sessions.values())
        )
        gate_control_write_ms = (gate_finished - gate_started) / 1_000_000
        log(
            "start gate released: "
            f"{gate_control_write_ms:.3f} ms "
            "across SSH stdin writes"
        )
        _wait_for_workers(
            tuple(sessions.values()),
            plan.remote.run_timeout_s + 60,
        )
    except BaseException as exc:
        _abort_sessions(sessions.values())
        if isinstance(exc, KeyboardInterrupt):
            raise
        for name in sessions:
            errors[name] = str(exc)
        return sessions, errors, gate_control_write_ms
    for name, session in sessions.items():
        if session.result is None:
            errors[name] = (
                session.protocol_error
                or f"worker exited {session.exit_code} without RESULT_JSON"
            )
        elif not session.result.get("success"):
            errors[name] = str(
                session.result.get("error", "worker reported failure")
            )
        if session.exit_code not in (0, None):
            errors.setdefault(
                name, f"worker ssh process exited {session.exit_code}"
            )
    return sessions, errors, gate_control_write_ms


