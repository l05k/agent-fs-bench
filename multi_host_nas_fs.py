#!/usr/bin/env python3
"""Run a concurrent filesystem experiment against one NAS from many hosts.

The control machine reads a YAML plan that names the SSH hosts, the NAS mount
and the workload. It then:

1. checks SSH/Python/mount prerequisites in parallel;
2. deploys this same file as a worker to every host;
3. mounts the NAS on every host in parallel, rejecting pre-existing mounts
   that point at a different source;
4. starts every worker, waits for all of them to reach the start gate, and
   releases them together;
5. collects per-host metrics and writes local reports.

The workload writes only below ``nas.run_root``. Every host gets a private
``hosts/<name>/`` tree, and all hosts also contend in one ``shared/``
directory. It measures private create/fsync/read/stat/rename phases plus
shared-directory create/fsync/read/stat/delete phases.

This script intentionally has no third-party dependencies. The YAML reader is
a strict subset parser for this plan format: block mappings/sequences, quoted
or plain scalars, comments, booleans, null and numbers. Anchors, aliases, flow
collections and multi-document streams are rejected rather than misread.

The worker runs from the deployed copy and receives its job as JSON. It never
mounts anything itself. Start with ``--check`` to validate a plan without
opening SSH connections.
"""

