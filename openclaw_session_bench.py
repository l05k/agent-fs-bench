def render_markdown(result: Dict[str, Any], template_text: str) -> str:
    try:
        return string.Template(template_text).substitute(
            build_markdown_context(result)
        )
    except KeyError as exc:
        name = exc.args[0] if exc.args else "<unknown>"
        raise BenchmarkError(
            f"Markdown template references unknown variable ${name}"
        ) from exc
    except ValueError as exc:
        raise BenchmarkError(f"invalid Markdown template: {exc}") from exc


def build_summary_lines(result: Dict[str, Any]) -> List[str]:
    latency = result["latency_ms"]["turn_transaction"]
    lines = [
        "turns={turns} events={new_events} elapsed={duration_actual_s:.3f}s "
        "turns/s={turns_per_s:.1f} payload={payload_mib_per_s:.2f} MiB/s".format(
            **result
        ),
        "turn tx: p50={p50} p95={p95} p99={p99} max={max}".format(
            p50=format_ms(latency["p50"]),
            p95=format_ms(latency["p95"]),
            p99=format_ms(latency["p99"]),
            max=format_ms(latency["max"]),
        ),
        "db={db} WAL peak={wal} checkpoint={checkpoint:.3f} ms "
        "integrity={integrity}".format(
            db=format_bytes(result["files"]["db_bytes_after"]),
            wal=format_bytes(result["files"]["wal_peak_bytes"]),
            checkpoint=result["final_checkpoint"]["elapsed_ms"],
            integrity=result["integrity_check"],
        ),
        f"target dir: {result.get('target_dir', 'n/a')}",
        f"results: {result['out_dir']}",
        f"report: {result['markdown_out']}",
    ]
    return lines


def print_result(result: Dict[str, Any]) -> None:
    for line in build_summary_lines(result):
        print(line)


def build_manifest_lines(result: Dict[str, Any]) -> List[str]:
    values = (
        ("created_at_utc", result.get("generated_at_utc")),
        ("command", result.get("command")),
        ("results_dir", result.get("out_dir")),
        ("target_dir", result.get("target_dir")),
        ("source_snapshot", result.get("source_snapshot")),
        ("python_version", result.get("python_version")),
        ("sqlite_version", result.get("sqlite_version")),
        ("database", result.get("db_path")),
        ("result_json", result.get("json_out")),
        ("markdown_report", result.get("markdown_out")),
        ("markdown_template", result.get("markdown_template")),
        ("markdown_template_source", result.get("markdown_template_source")),
        ("summary", result.get("summary_out")),
        ("turns", result.get("turns")),
        ("events", result.get("new_events")),
        ("integrity_check", result.get("integrity_check")),
    )
    return [
        f"{name}={shlex.quote(str(value))}"
        for name, value in values
    ]


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    args.invocation_argv = list(argv) if argv is not None else list(sys.argv[1:])
    results_dir = results_run_dir(SCRIPT_NAME, anchor=__file__)
    markdown_template: Optional[str] = None
    try:
        expand_user_paths(args)
        configure_output_paths(args, results_dir)
        validate_output_paths(args)
        markdown_template = load_markdown_template(args.markdown_template)
        overrides = parse_pragma_overrides(args.pragma)
        prepare_output_paths(args)
        result = run(args, overrides)
    except BenchmarkError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    except Exception as exc:
        print(f"error: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1

    result["json_out"] = str(args.json_out)
    result["markdown_out"] = str(args.markdown_out)
    result["manifest_out"] = str(args.manifest_out)
    result["summary_out"] = str(args.summary_out)
    result["markdown_template"] = str(args.markdown_template_out)
    result["markdown_template_source"] = (
        str(args.markdown_template)
        if args.markdown_template is not None
        else "built-in"
    )
    print_result(result)

    output_error = 0
    try:
        write_text(args.markdown_template_out, markdown_template)
        with open(args.json_out, "w", encoding="utf-8") as handle:
            json.dump(result, handle, indent=2, sort_keys=True)
            handle.write("\n")
        write_text(
            args.summary_out,
            "\n".join(build_summary_lines(result)),
        )
        write_text(
            args.manifest_out,
            "\n".join(build_manifest_lines(result)),
        )
        write_text(
            args.markdown_out,
            render_markdown(result, markdown_template),
        )
    except BenchmarkError as exc:
        print(f"error: {exc}", file=sys.stderr)
        output_error = 2
    except OSError as exc:
        print(f"error: cannot write output: {exc}", file=sys.stderr)
        output_error = 1

    if output_error:
        return output_error
    return 0 if result.get("integrity_check") == "ok" else 1


if __name__ == "__main__":
    sys.exit(main())
