def validate_fixtures(fixture_dir: Path) -> dict[str, Any]:
    """Fail fast on missing fixtures before the worktree is created."""
    if not fixture_dir.is_dir():
        raise WorkflowError(
            f"fixture directory not found: {fixture_dir}\n"
            "Copy data/mini-dev-workflow next to this script, or pass "
            "--fixture-dir."
        )
    series_path = fixture_dir / DEFAULT_SERIES
    series = load_json(series_path)

    base_commit = series.get("base_commit")
    commits = series.get("commits")
    if not isinstance(base_commit, str) or not base_commit:
        raise WorkflowError(f"{series_path}: invalid base_commit")
    if not isinstance(commits, list) or not commits:
        raise WorkflowError(f"{series_path}: invalid commits list")

    missing: list[str] = []
    for commit in commits:
        if not isinstance(commit, dict) or not isinstance(commit.get("id"), str):
            raise WorkflowError(f"{series_path}: invalid commit entry")
        if not isinstance(commit.get("message"), str):
            raise WorkflowError(f"{series_path}: commit {commit['id']} has no message")
        files = commit.get("files")
        if not isinstance(files, list) or not all(isinstance(f, str) for f in files):
            raise WorkflowError(f"{series_path}: commit {commit['id']} has invalid files")
        for command_file in ("search_commands", "read_commands", "edit_commands"):
            filename = commit.get(command_file)
            if not isinstance(filename, str) or not filename:
                raise WorkflowError(
                    f"{series_path}: commit {commit['id']} has no {command_file}"
                )
            if not (fixture_dir / filename).is_file():
                missing.append(filename)
    if missing:
        raise WorkflowError(
            "fixtures reference missing command files in "
            f"{fixture_dir}: {', '.join(sorted(set(missing)))}"
        )
    return series


def missing_dependencies(*, require_fstype: bool = False) -> list[str]:
    missing = [name for name in CORE_COMMANDS if shutil.which(name) is None]
    if require_fstype and shutil.which("findmnt") is None:
        missing.append("findmnt")
    for alternatives in BUILD_COMMANDS:
        if not any(shutil.which(name) for name in alternatives):
            missing.append(" or ".join(alternatives))
    return missing


def available_package_manager() -> str | None:
    for manager in PACKAGE_MANAGERS:
        if shutil.which(manager):
            return manager
    return None


def install_dependencies(manager: str) -> None:
    update_cmd, install_cmd = PACKAGE_MANAGERS[manager]
    if os.geteuid() == 0:
        prefix: list[str] = []
    else:
        sudo = shutil.which("sudo")
        if not sudo:
            raise WorkflowError("dependency installation requires root or sudo")
        prefix = [sudo]

    for command in (update_cmd, install_cmd):
        if not command:
            continue
        argv = [*prefix, *command]
        print(f"Installing dependencies: {shlex.join(argv)}", file=sys.stderr)
        run_command(
            argv,
            cwd=Path("/"),
            what=f"installing dependencies with {manager}",
            inherit_stdio=True,
            extra_env={"DEBIAN_FRONTEND": "noninteractive"},
        )


def ensure_dependencies(install: bool, *, require_fstype: bool = False) -> None:
    missing = missing_dependencies(require_fstype=require_fstype)
    if missing and install:
        manager = available_package_manager()
        if manager is None:
            raise WorkflowError(
                "missing dependencies and no supported package manager was found: "
                + ", ".join(missing)
            )
        install_dependencies(manager)
        missing = missing_dependencies(require_fstype=require_fstype)

    if missing:
        raise WorkflowError(
            "missing dependencies: "
            + ", ".join(missing)
            + "\nRerun with --install-deps or install them manually."
        )
    print("Dependency check passed.", file=sys.stderr)


def detect_filesystem(path: Path) -> str | None:
    findmnt = shutil.which("findmnt")
    if not findmnt:
        return None
    proc = subprocess.run(
        [findmnt, "-T", str(path), "-n", "-o", "FSTYPE"],
        text=True,
        encoding="utf-8",
        errors="replace",
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        check=False,
    )
    value = proc.stdout.strip()
    return value or None


def existing_ancestor(path: Path) -> Path:
    probe = path
    while not probe.exists() and probe != probe.parent:
        probe = probe.parent
    return probe


def require_filesystem(path: Path, expected: str | None, label: str) -> None:
    if not expected:
        return
    probe = existing_ancestor(path)
    actual = detect_filesystem(probe)
    if actual is None:
        raise WorkflowError(
            f"cannot determine filesystem for {label}; install findmnt or "
            "remove the filesystem requirement"
        )
    if actual != expected:
        raise WorkflowError(
            f"{label} must be on {expected}, but {probe} is on {actual}"
        )


def default_source_repo(worktree: Path) -> Path:
    """Return the source repository path next to ``--repo``.

    The repository must sit on the filesystem under test: ``git worktree add``
    keeps the index, refs and objects in the source repository, so anything
    placed elsewhere is timed against the wrong filesystem.
    """
    return worktree.parent / f"{worktree.name}{SOURCE_REPO_SUFFIX}"


def ensure_source_repo(source_repo: Path, fixture_dir: Path, *, verbose: bool) -> None:
    """Create the source repository from the committed bundle when absent."""
    if source_repo.exists():
        return
    bundle = fixture_dir / DEFAULT_BUNDLE
    if not bundle.is_file():
        raise WorkflowError(
            f"cannot create source repository {source_repo}: "
            f"bundle not found at {bundle}"
        )
    source_repo.parent.mkdir(parents=True, exist_ok=True)
    run_command(
        ["git", "-c", "core.hooksPath=/dev/null", "clone", "--quiet",
         str(bundle), str(source_repo)],
        cwd=fixture_dir,
        what=f"extracting source repository from {bundle}",
        verbose=verbose,
    )


def prepare_source_repo(
    source_repo: Path, fixture_dir: Path, *, verbose: bool
) -> int:
    """Ensure the source repository exists; return its one-off setup time.

    Creation happens before any timed section, so later runs reuse the
    repository and pay nothing. The cost is reported separately instead of
    being folded into a reused-run measurement.
    """
    if source_repo.exists():
        return 0
    start = time.perf_counter_ns()
    ensure_source_repo(source_repo, fixture_dir, verbose=verbose)
    return elapsed_ms(start)


def resolve_source_repo(source_repo: Path, *, verbose: bool) -> Path:
    """Validate the source repository and return the directory to run git in."""
    if not source_repo.exists():
        raise WorkflowError(
            f"source repository not found: {source_repo}\n"
            "It is created from the fixture bundle on first use; if that "
            "failed, remove the path and rerun."
        )
    if not source_repo.is_dir():
        raise WorkflowError(
            f"source repository must be a Git checkout, not a file: {source_repo}\n"
            f"If this is source-repo.bundle, extract it first: "
            f"git clone {source_repo} <dir>"
        )
    if not (source_repo / ".git").exists():
        raise WorkflowError(
            f"{source_repo} is not a Git repository; "
            "remove it and rerun so it is recreated from the bundle"
        )
    run_command(
        ["git", "-c", "core.hooksPath=/dev/null", "rev-parse", "--git-dir"],
        cwd=source_repo,
        what=f"opening source repository {source_repo}",
        verbose=verbose,
    )
    return source_repo


def active_marker_path(source_repo: Path) -> Path:
    git_dir = Path(
        git_text(
            source_repo,
            ["rev-parse", "--absolute-git-dir"],
            what="resolving source repository Git directory",
        )
    )
    return git_dir / ACTIVE_MARKER


def marker_owner_is_running(marker: Path) -> bool:
    try:
        first_line = marker.read_text(encoding="ascii").splitlines()[0]
        pid = int(first_line)
    except (OSError, ValueError, IndexError):
        return False
    if pid == os.getpid():
        return False
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def remove_worktree(
    source_repo: Path,
    *,
    worktree: Path,
    verbose: bool,
) -> None:
    errors: list[str] = []
    if worktree.exists():
        try:
            run_git(
                source_repo,
                ["worktree", "remove", "--force", str(worktree)],
                what="removing the benchmark worktree",
                verbose=verbose,
            )
        except WorkflowError as exc:
            errors.append(str(exc))
    try:
        run_git(
            source_repo,
            ["worktree", "prune"],
            what="pruning stale worktree metadata",
            verbose=verbose,
        )
    except WorkflowError as exc:
        errors.append(str(exc))
    if errors:
        raise WorkflowError("worktree cleanup failed: " + "; ".join(errors))


def cleanup_run(
    source_repo: Path,
    *,
    worktree: Path,
    marker: Path,
    verbose: bool,
) -> None:
    errors: list[str] = []
    try:
        remove_worktree(source_repo, worktree=worktree, verbose=verbose)
    except WorkflowError as exc:
        errors.append(str(exc))
    if not worktree.exists():
        try:
            marker.unlink(missing_ok=True)
        except OSError as exc:
            errors.append(f"cannot remove ownership marker {marker}: {exc}")
    if errors:
        raise WorkflowError("cleanup failed: " + "; ".join(errors))


def begin_run(
    source_repo: Path,
    *,
    worktree: Path,
    base_commit: str,
    marker: Path,
    verbose: bool,
) -> None:
    if marker.exists():
        if marker_owner_is_running(marker):
            raise WorkflowError(
                f"another mini-dev-workflow run owns this source repository: {marker}"
            )
        print(
            f"Recovering after an interrupted run: {worktree}",
            file=sys.stderr,
        )
        cleanup_run(
            source_repo,
            worktree=worktree,
            marker=marker,
            verbose=verbose,
        )

    if worktree.exists():
        if not worktree.is_dir():
            raise WorkflowError(f"--repo exists and is not a directory: {worktree}")
        entries = list(worktree.iterdir())
        if entries and any(not entry.is_dir() or any(entry.iterdir()) for entry in entries):
            raise WorkflowError(
                f"--repo must be absent or empty for a fresh worktree: {worktree}"
            )
        for entry in entries:
            entry.rmdir()
        worktree.rmdir()

    try:
        worktree.parent.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise WorkflowError(f"cannot create parent of --repo {worktree}: {exc}") from exc

    if not has_local_commit(source_repo, base_commit):
        raise WorkflowError(
            f"source repository {source_repo} does not contain base commit "
            f"{base_commit}; regenerate the fixture with "
            "tools/gen_mini_source_repo.py"
        )

    marker.write_text(f"{os.getpid()}\n{time.time_ns()}\n", encoding="ascii")


def has_local_commit(repo: Path, revision: str) -> bool:
    # ``rev-parse --verify --quiet`` exits 1 for an unresolvable revision;
    # ``cat-file -e`` exits 128, which would bypass the friendly error below.
    result = run_command(
        [
            "git",
            "-c",
            "core.hooksPath=/dev/null",
            "rev-parse",
            "--verify",
            "--quiet",
            f"{revision}^{{commit}}",
        ],
        cwd=repo,
        what=f"checking for local commit {revision}",
        capture_stdout=True,
        allow_codes=(0, 1),
    )
    return result.stdout.strip() != ""


def loose_object_count(repo: Path) -> int:
    """Count loose objects so run-to-run history growth stays visible."""
    objects = repo / ".git" / "objects"
    if not objects.is_dir():
        return 0
    count = 0
    for entry in objects.iterdir():
        if len(entry.name) == 2 and entry.is_dir():
            count += sum(1 for _ in entry.iterdir())
    return count


def verify_tree(worktree: Path, commit_id: str) -> dict[str, Any]:
    actual = git_text(
        worktree,
        ["rev-parse", "HEAD^{tree}"],
        what=f"reading replayed tree for {commit_id}",
    )
    expected = git_text(
        worktree,
        ["rev-parse", f"{commit_id}^{{tree}}"],
        what=f"reading target tree for {commit_id}",
    )
    if actual != expected:
        raise WorkflowError(
            f"tree mismatch for {commit_id}: expected {expected}, got {actual}"
        )
    return {"commit": commit_id, "tree": actual, "ok": True}


def record_checkpoint(step: int, phase: str, steps: list[dict[str, Any]]) -> None:
    steps.append({"step": f"checkpoint: {phase}", "ms": 0})


def summary_text(result: dict[str, Any]) -> str:
    lines = [f"{result.get('workflow', 'workflow')} ({result.get('execution_mode', '?')})"]
    if result.get("repo"):
        lines.append(f"repo={result['repo']} source={result.get('source_repo')}")
    lines.append(
        f"success={result.get('success')} filesystem={result.get('filesystem')}"
    )
    if result.get("elapsed_ms") is not None:
        lines.append(
            f"elapsed_ms={result['elapsed_ms']} "
            f"preparation_ms={result.get('preparation_ms')} "
            f"cleanup_ms={result.get('cleanup_ms')} "
            f"unattributed_ms={result.get('unattributed_ms')}"
        )
        lines.append(
            f"jobs={result.get('jobs')} checkpoints={result.get('checkpoint_count')}"
        )
        lines.append(f"fsync_mode: {result.get('fsync_mode', '?')}")
        lines.append(f"cache_state: {result.get('cache_state', '?')}")
        lines.append(
            f"loose_objects: {result.get('loose_objects_before')} -> "
            f"{result.get('loose_objects_after')}"
        )
    error = result.get("error")
    if error:
        lines.append(f"error: {error}")
    return "\n".join(lines) + "\n"


def manifest_text(result: dict[str, Any], argv: list[str]) -> str:
    return "\n".join(
        [
            f"workload: {result.get('workflow', '?')}",
            f"generated_at_utc: {utc_run_id()}",
            f"command: {shlex.join([sys.executable, Path(__file__).name, *argv])}",
            f"platform: {platform.platform()}",
            f"python_version: {sys.version.split()[0]}",
            f"target_repo: {result.get('repo', '?')}",
            f"source_repo: {result.get('source_repo', '?')}",
            f"git_dir: {result.get('git_dir', '?')}",
            f"jobs: {result.get('jobs')}",
            f"fsync_mode: {result.get('fsync_mode', '?')}",
            f"cache_state: {result.get('cache_state', '?')}",
            f"required_filesystem: {result.get('required_filesystem')}",
        ]
    ) + "\n"


def write_result(
    results_dir: Path,
    result: dict[str, Any],
    argv: list[str],
) -> None:
    output = results_dir / "result.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(result, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    (results_dir / "summary.txt").write_text(summary_text(result), encoding="utf-8")
    (results_dir / "manifest.txt").write_text(
        manifest_text(result, argv), encoding="utf-8"
    )
    print(f"Results written to {output}", file=sys.stderr)


def resolve_jobs(args: argparse.Namespace) -> int:
    """Pin build parallelism.

    The fixture has two translation units, so a larger ``-j`` only adds
    scheduling noise. An explicit ``--jobs`` is still honoured but clamped,
    and the value actually used is reported in ``result.json``.
    """
    return min(args.jobs, FIXED_JOBS) if args.jobs > 0 else FIXED_JOBS


def run_workflow(args: argparse.Namespace) -> dict[str, Any]:
    worktree = Path(args.repo).expanduser().absolute()
    fixture_dir = Path(args.fixture_dir).expanduser().absolute()
    source_repo = default_source_repo(worktree)
    series_path = fixture_dir / DEFAULT_SERIES

    series = validate_fixtures(fixture_dir)
    base_commit = series["base_commit"]
    commits = series["commits"]
    commit_ids = [commit["id"] for commit in commits]

    source_setup_ms = prepare_source_repo(
        source_repo, fixture_dir, verbose=args.verbose
    )
    source_repo = resolve_source_repo(source_repo, verbose=args.verbose)
    require_filesystem(source_repo, args.require_fstype, "source repository")
    filesystem = detect_filesystem(source_repo)

    preparation_start = time.perf_counter_ns()
    validate_source_repository(source_repo, base_commit=base_commit, commit_ids=commit_ids)
    marker = active_marker_path(source_repo)
    objects_before = loose_object_count(source_repo)

    jobs = resolve_jobs(args)
    steps: list[dict[str, Any]] = []
    assertions: list[dict[str, Any]] = []
    checkpoint_step = 0
    cleanup_error: str | None = None
    cleanup_ms: int | None = None
    preparation_ms: int | None = None
    preparation_steps: list[dict[str, Any]] = []
    workflow_ms: int | None = None
    success = False
    error: str | None = None
    timed_start: int | None = None
    timed_end: int | None = None
    repo_action = "worktree-add"
    source_repo_action = "cloned-bundle" if source_setup_ms else "reused"

    try:
        begin_run(
            source_repo,
            worktree=worktree,
            base_commit=base_commit,
            marker=marker,
            verbose=args.verbose,
        )

        prune_start = time.perf_counter_ns()
        run_git(
            source_repo,
            ["worktree", "prune"],
            what="pruning stale worktree metadata",
            verbose=args.verbose,
        )
        preparation_steps.append(
            {"step": "worktree: prune", "ms": elapsed_ms(prune_start)}
        )

        add_start = time.perf_counter_ns()
        run_git(
            source_repo,
            ["worktree", "add", "--detach", str(worktree), base_commit],
            what="creating the benchmark worktree",
            verbose=args.verbose,
        )
        preparation_steps.append(
            {"step": "worktree: add", "ms": elapsed_ms(add_start)}
        )

        preparation_ms = elapsed_ms(preparation_start)
        print(
            f"Worktree prepared at {worktree} ({repo_action}, {preparation_ms} ms).",
            file=sys.stderr,
        )
        timed_start = time.perf_counter_ns()

        checkpoint_step += 1
        record_checkpoint(checkpoint_step, "worktree", steps)

        initial = run_command(
            ["make", f"-j{jobs}"],
            cwd=worktree,
            what="initial build",
            verbose=args.verbose,
        )
        steps.append({"step": "initial-build: make", "ms": initial.ms})

        checkpoint_step += 1
        record_checkpoint(checkpoint_step, "initial-build", steps)

        for commit in commits:
            commit_id = commit["id"]
            message = commit["message"]
            files = commit["files"]

            commands: list[tuple[str, str]] = []
            for command_file in ("search_commands", "read_commands", "edit_commands"):
                commands.append((command_file, commit[command_file]))

            for phase, filename in commands:
                category = phase.removesuffix("_commands")
                load_start = time.perf_counter_ns()
                loaded = load_commands(fixture_dir / filename)
                steps.append(
                    {
                        "step": f"{category}-load: {commit_id}",
                        "ms": elapsed_ms(load_start),
                    }
                )
                for idx, command in enumerate(loaded, 1):
                    result = run_shell(
                        command,
                        cwd=worktree,
                        what=f"{category} command for {commit_id} #{idx}",
                        verbose=args.verbose,
                    )
                    steps.append(
                        {"step": f"{category}: {commit_id} #{idx}", "ms": result.ms}
                    )
                    if category == "edit":
                        checkpoint_step += 1
                        record_checkpoint(
                            checkpoint_step, f"{commit_id} #{idx}", steps
                        )

            incremental = run_command(
                ["make", f"-j{jobs}"],
                cwd=worktree,
                what=f"incremental build for {commit_id}",
                verbose=args.verbose,
            )
            steps.append(
                {"step": f"incremental-build: {commit_id}", "ms": incremental.ms}
            )

            checkpoint_step += 1
            record_checkpoint(
                checkpoint_step, f"incremental-build {commit_id}", steps
            )

            status = run_git(
                worktree,
                ["status", "--short"],
                what=f"git status for {commit_id}",
                verbose=args.verbose,
            )
            steps.append({"step": f"git-status: {commit_id}", "ms": status.ms})

            diff = run_git(
                worktree,
                ["diff", "--stat", "--", *files],
                what=f"git diff for {commit_id}",
                verbose=args.verbose,
            )
            steps.append({"step": f"git-diff: {commit_id}", "ms": diff.ms})

            add = run_git(
                worktree,
                ["add", "--", *files],
                what=f"git add for {commit_id}",
                verbose=args.verbose,
            )
            steps.append({"step": f"git-add: {commit_id}", "ms": add.ms})

            commit_result = run_git(
                worktree,
                [
                    "-c",
                    "user.name=YoloFS Bench",
                    "-c",
                    "user.email=bench@yolo.local",
                    "commit",
                    "--no-gpg-sign",
                    "-m",
                    message,
                ],
                what=f"git commit for {commit_id}",
                verbose=args.verbose,
            )
            steps.append({"step": f"git-commit: {commit_id}", "ms": commit_result.ms})

            checkpoint_step += 1
            record_checkpoint(checkpoint_step, f"git-commit {commit_id}", steps)
            verify_start = time.perf_counter_ns()
            assertions.append(verify_tree(worktree, commit_id))
            steps.append(
                {"step": f"tree-verify: {commit_id}", "ms": elapsed_ms(verify_start)}
            )

        success = True
    except WorkflowError as exc:
        error = str(exc)
    except KeyboardInterrupt:
        error = "interrupted"
    except Exception as exc:
        error = f"unexpected error: {exc}"
        if args.verbose:
            traceback.print_exc()
    finally:
        if preparation_ms is None:
            preparation_ms = elapsed_ms(preparation_start)
        timed_end = time.perf_counter_ns()
        if timed_start is not None:
            workflow_ms = (timed_end - timed_start) // 1_000_000
        else:
            workflow_ms = 0
        cleanup_start = time.perf_counter_ns()
        if marker.exists():
            try:
                cleanup_run(
                    source_repo,
                    worktree=worktree,
                    marker=marker,
                    verbose=args.verbose,
                )
            except WorkflowError as exc:
                cleanup_error = str(exc)
        cleanup_ms = elapsed_ms(cleanup_start)

    if cleanup_error:
        success = False
        error = f"{error}; {cleanup_error}" if error else cleanup_error

    unattributed_ms = max(0, (workflow_ms or 0) - sum(
        step["ms"] for step in steps if not step["step"].startswith("checkpoint: ")
    ))

    return {
        "schema_version": 3,
        "workflow": "mini-dev-workflow",
        "execution_mode": "git-worktree",
        "success": success,
        "error": error,
        "repo": str(worktree),
        "repo_action": repo_action,
        "source_repo": str(source_repo),
        "source_repo_action": source_repo_action,
        "source_setup_ms": source_setup_ms,
        "git_dir": str(source_repo / ".git"),
        "preparation_ms": preparation_ms,
        "preparation_steps": preparation_steps,
        "fixture_dir": str(fixture_dir),
        "series": str(series_path),
        "worktree_removed": not worktree.exists(),
        "filesystem": filesystem,
        "required_filesystem": args.require_fstype,
        "base_commit": base_commit,
        "checkpoint_count": checkpoint_step,
        "jobs": jobs,
        "elapsed_ms": workflow_ms,
        "unattributed_ms": unattributed_ms,
        "cleanup_ms": cleanup_ms,
        "loose_objects_before": objects_before,
        "loose_objects_after": loose_object_count(source_repo),
        "fsync_mode": FSYNC_MODE,
        "cache_state": CACHE_STATE,
        "steps": steps,
        "tree_assertions": assertions,
    }


def validate_source_repository(
    source_repo: Path,
    *,
    base_commit: str,
    commit_ids: list[str],
) -> None:
    problems = [
        revision
        for revision in (base_commit, *commit_ids)
        if not has_local_commit(source_repo, revision)
    ]
    if problems:
        raise WorkflowError(
            f"source repository {source_repo} is missing fixture commits: "
            f"{', '.join(problems)}; remove that directory so it is recreated "
            "from the fixture bundle, or regenerate the fixture with "
            "tools/gen_mini_source_repo.py"
        )
    status = git_text(
        source_repo,
        ["status", "--porcelain=v1", "--untracked-files=all", "--ignored"],
        what="checking source repository cleanliness",
    )
    if status:
        preview = "\n".join(status.splitlines()[:20])
        raise WorkflowError(
            "source repository must be clean before a run:\n" + preview
        )


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run the mini-dev-workflow in a disposable Git worktree on the "
            "filesystem under test."
        )
    )
    parser.add_argument(
        "--repo",
        required=True,
        help=(
            "worktree path on the filesystem under test; must be absent or "
            "empty and is removed after the run"
        ),
    )
    parser.add_argument(
        "--fixture-dir",
        default=str(DEFAULT_FIXTURE_DIR),
        help="directory containing the checked-in workflow fixtures",
    )
    parser.add_argument(
        "--require-fstype",
        default=None,
        help="require this filesystem type for --repo, for example ext4",
    )
    parser.add_argument(
        "--install-deps",
        action="store_true",
        help="install missing build dependencies before running",
    )
    parser.add_argument(
        "--jobs",
        type=int,
        default=0,
        help=f"build parallelism (default and maximum: {FIXED_JOBS})",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="show command output",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    args = parse_args(argv)
    results_dir = results_run_dir(SCRIPT_NAME, anchor=__file__)

    try:
        ensure_ascii_source()
        validate_fixtures(Path(args.fixture_dir).expanduser().absolute())
        require_linux()
        ensure_dependencies(
            args.install_deps,
            require_fstype=bool(args.require_fstype),
        )
        result = run_workflow(args)
    except WorkflowError as exc:
        result = {
            "schema_version": 3,
            "workflow": "mini-dev-workflow",
            "success": False,
            "error": str(exc),
        }
    except KeyboardInterrupt:
        result = {
            "schema_version": 3,
            "workflow": "mini-dev-workflow",
            "success": False,
            "error": "interrupted",
        }
    except Exception as exc:
        result = {
            "schema_version": 3,
            "workflow": "mini-dev-workflow",
            "success": False,
            "error": f"unexpected error: {exc}",
        }

    write_result(results_dir, result, argv)
    if result.get("success"):
        print(
            "mini-dev-workflow completed: "
            f"{result.get('elapsed_ms', 0)} ms, "
            f"{len(result.get('steps', []))} steps, "
            f"{result.get('checkpoint_count', 0)} checkpoint boundaries"
        )
        return 0

    print(f"mini-dev-workflow failed: {result.get('error')}", file=sys.stderr)
    return 1


def _handle_sigterm(_signum: int, _frame: Any) -> None:
    raise KeyboardInterrupt


if __name__ == "__main__":
    signal.signal(signal.SIGTERM, _handle_sigterm)
    raise SystemExit(main())
