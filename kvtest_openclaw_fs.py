def expand_user_paths(args: argparse.Namespace) -> None:
    """Expand ``~`` and make relative paths absolute against the cwd."""
    for name in ("target_dir", "build_dir"):
        path = getattr(args, name)
        if path is not None:
            setattr(args, name, path.expanduser().resolve())


def ensure_directory(path: Path, what: str) -> None:
    """Create ``path`` with an actionable error when that is impossible."""
    try:
        path.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise BenchmarkError(f"cannot create {what} {path}: {exc}") from exc


def download(url: str, destination: Path) -> None:
    """Download ``url`` to ``destination`` atomically."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    partial = destination.with_suffix(destination.suffix + ".part")
    try:
        with urllib.request.urlopen(url, timeout=120) as response:
            partial.write_bytes(response.read())
    except Exception as exc:
        partial.unlink(missing_ok=True)
        raise BenchmarkError(f"failed to download {url}: {exc}") from exc
    partial.replace(destination)


def ensure_sources(build_dir: Path, force: bool) -> Dict[str, Path]:
    """Fetch the amalgamation and ``kvtest.c``; return both paths."""
    ensure_directory(build_dir, "build directory")
    archive = build_dir / SQLITE_AMALGAMATION
    source = build_dir / "kvtest.c"
    if force or not archive.exists():
        download(SQLITE_AMALGAMATION_URL, archive)
    if force or not source.exists():
        download(KVTEST_URL, source)

    inner = archive.with_suffix("")
    amalgamation = inner / "sqlite3.c"
    header = inner / "sqlite3.h"
    if not amalgamation.exists() or not header.exists():
        shutil.rmtree(inner, ignore_errors=True)
        shutil.unpack_archive(str(archive), str(build_dir))
        if not amalgamation.exists():
            raise BenchmarkError(
                f"{archive} did not contain sqlite3.c as expected"
            )
    return {"kvtest": source, "sqlite3": amalgamation, "sqlite3_h": header}


def build(build_dir: Path, sources: Dict[str, Path], force: bool) -> Path:
    """Compile ``kvtest`` and return the binary path."""
    binary = build_dir / "kvtest"
    newest_source = max(
        path.stat().st_mtime for path in (sources["kvtest"], sources["sqlite3"])
    )
    if binary.exists() and not force and binary.stat().st_mtime >= newest_source:
        return binary

    compiler = os.environ.get("CC") or shutil.which("cc") or shutil.which("gcc")
    if not compiler:
        raise BenchmarkError(
            "no C compiler found; set CC or install cc/gcc on the test machine"
        )
    command = [
        compiler,
        "-O2",
        "-o",
        str(binary),
        str(sources["kvtest"]),
        str(sources["sqlite3"]),
        "-DSQLITE_THREADSAFE=0",
        "-DSQLITE_OMIT_LOAD_EXTENSION",
        "-lm",
    ]
    proc = subprocess.run(command, capture_output=True, text=True)
    if proc.returncode != 0:
        raise BenchmarkError(
            "failed to compile kvtest:\n"
            + shlex.join(command)
            + "\n"
            + proc.stdout
            + proc.stderr
        )
    return binary


def run_command(command: Sequence[str]) -> subprocess.CompletedProcess:
    proc = subprocess.run(command, capture_output=True, text=True)
    if proc.returncode != 0:
        raise BenchmarkError(
            f"command failed ({proc.returncode}): {shlex.join(command)}\n"
            + proc.stdout
            + proc.stderr
        )
    return proc


PARSE_PATTERNS = {
    "microseconds_per_write": re.compile(r"Microseconds per BLOB write:\s*([0-9.]+)"),
    "write_rate_mb_s": re.compile(r"Content write rate:\s*([0-9.]+)"),
    "total_elapsed_s": re.compile(r"Total elapsed time:\s*([0-9.]+)"),
    "page_size": re.compile(r"Database page size:\s*(\d+)"),
}


def parse_kvtest_output(text: str) -> Dict[str, Any]:
    parsed: Dict[str, Any] = {}
    for name, pattern in PARSE_PATTERNS.items():
        match = pattern.search(text)
        if match:
            value = match.group(1)
            parsed[name] = float(value) if "." in value else int(value)
    if "microseconds_per_write" not in parsed:
        raise BenchmarkError(
            "could not parse kvtest output; expected "
            "'Microseconds per BLOB write'. Full output:\n" + text
        )
    return parsed


def file_size(path: Path) -> int:
    try:
        return path.stat().st_size
    except FileNotFoundError:
        return 0


def reached_synchronous(args: argparse.Namespace) -> str:
    """Return the synchronous mode kvtest will run with."""
    return "OFF" if args.nosync else "FULL"


def database_pragmas(
    db_path: Path, reached_synchronous: str
) -> Dict[str, Any]:
    """Read back the pragmas that were actually in effect.

    ``synchronous``, ``wal_autocheckpoint``, ``cache_size`` and ``mmap_size``
    are connection-scoped in SQLite, so a fresh inspection connection cannot
    observe the values the benchmark used. Those are reported from the
    invocation instead; only the persistent header and page counts are read.
    """
    conn = sqlite3.connect(str(db_path))
    try:
        values: Dict[str, Any] = {}
        for name in (
            "journal_mode",
            "journal_size_limit",
            "page_size",
            "page_count",
            "freelist_count",
        ):
            try:
                row = conn.execute(f"PRAGMA {name}").fetchone()
                values[name] = row[0] if row else None
            except sqlite3.Error as exc:
                values[name] = f"unavailable: {exc}"
        try:
            values["integrity_check"] = conn.execute(
                "PRAGMA integrity_check"
            ).fetchone()[0]
        except sqlite3.Error as exc:
            values["integrity_check"] = f"unavailable: {exc}"
        values["synchronous_name"] = reached_synchronous
        return values
    finally:
        conn.close()


def remove_database(db_path: Path) -> None:
    for suffix in ("", "-wal", "-shm", "-journal"):
        Path(str(db_path) + suffix).unlink(missing_ok=True)


def run(args: argparse.Namespace) -> Dict[str, Any]:
    build_dir = args.build_dir or (Path(__file__).resolve().parent / "build")
    sources = ensure_sources(build_dir, args.force_download)
    binary = build(build_dir, sources, args.force_download)

    target_dir = args.target_dir
    ensure_directory(target_dir, "target directory")
    db_path = target_dir / DB_FILENAME
    remove_database(db_path)

    init_command = [
        str(binary),
        "init",
        str(db_path),
        "--count",
        str(args.count),
        "--size",
        str(args.size),
        "--variance",
        str(args.variance),
    ]
    setup_started = time.perf_counter()
    init_proc = run_command(init_command)
    setup_elapsed = time.perf_counter() - setup_started

    conn = sqlite3.connect(str(db_path))
    try:
        db_bytes_after_init = file_size(db_path)
        page_size = conn.execute("PRAGMA page_size").fetchone()[0]
    finally:
        conn.close()

    run_command_argv = [
        str(binary),
        "run",
        str(db_path),
        "--count",
        str(args.count),
        "--update",
        "--random",
        "--multitrans",
        "--jmode",
        args.jmode,
        "--cache-size",
        str(args.cache_size),
        "--mmap",
        str(args.mmap),
    ]
    if args.nosync:
        run_command_argv.append("--nosync")

    repeats: List[Dict[str, Any]] = []
    stdout_chunks: List[str] = [
        "# init: " + shlex.join(init_command),
        init_proc.stdout,
        "",
    ]
    for index in range(args.repeats):
        # kvtest writes the same rows again each time; that is intentional,
        # so later repeats measure overwrite-with-existing-rows.
        wal_path = Path(str(db_path) + "-wal")
        before_wal = file_size(wal_path)
        proc = run_command(run_command_argv)
        parsed = parse_kvtest_output(proc.stdout)
        repeats.append(
            {
                "index": index + 1,
                "argv": run_command_argv,
                "parsed": parsed,
                "wal_bytes_before": before_wal,
                "wal_bytes_after": file_size(wal_path),
                "raw_stdout": proc.stdout,
            }
        )
        stdout_chunks.append(f"# run {index + 1}: " + shlex.join(run_command_argv))
        stdout_chunks.append(proc.stdout)

    final_wal_path = Path(str(db_path) + "-wal")
    final_shm_path = Path(str(db_path) + "-shm")
    db_pragmas = database_pragmas(db_path, reached_synchronous(args))
    db_bytes_final = file_size(db_path)
    wal_bytes_final = file_size(final_wal_path)
    shm_bytes_final = file_size(final_shm_path)

    best = min(entry["parsed"]["microseconds_per_write"] for entry in repeats)
    worst = max(entry["parsed"]["microseconds_per_write"] for entry in repeats)

    return {
        "workload": "sqlite-kvtest-openclaw-multitrans",
        "command": shlex.join([sys.executable, str(Path(sys.argv[0])), *sys.argv[1:]]),
        "sqlite_version": sqlite3.sqlite_version,
        "sqlite_build_version": SQLITE_VERSION,
        "kvtest_source": KVTEST_URL,
        "amalgamation_source": SQLITE_AMALGAMATION_URL,
        "platform": platform.platform(),
        "python_version": sys.version.split()[0],
        "cc": os.environ.get("CC") or "cc",
        "target_dir": str(target_dir),
        "db_path": str(db_path),
        "payload_bytes": args.size,
        "payload_variance": args.variance,
        "writes": args.count,
        "jmode": args.jmode,
        "nosync": args.nosync,
        "cache_size_kib": args.cache_size,
        "mmap_bytes": args.mmap,
        "repeats": args.repeats,
        "setup_elapsed_s": setup_elapsed,
        "page_size": db_pragmas.get("page_size") or page_size,
        "openclaw_settings": OPENCLAW_SETTINGS,
        "reached_settings": {
            **REACHED_SETTINGS,
            "synchronous": reached_synchronous(args),
            "cache_size": -args.cache_size,
            "mmap_size": args.mmap,
        },
        "settings_gap": [
            "synchronous: OpenClaw NORMAL, kvtest offers only FULL or OFF",
            "busy_timeout: OpenClaw 5000 ms, kvtest cannot set it",
            "journal_size_limit: OpenClaw 64 MiB, kvtest cannot set it",
            "wal_autocheckpoint: OpenClaw 0, kvtest default 1000",
            "auto_vacuum: OpenClaw INCREMENTAL on fresh db, kvtest cannot set it",
            "no secondary indexes, no FTS5, single kv table",
        ],
        "results": repeats,
        "microseconds_per_write": {
            "best": best,
            "worst": worst,
            "all": [entry["parsed"]["microseconds_per_write"] for entry in repeats],
        },
        "pragmas": db_pragmas,
        "files": {
            "db_bytes_after_init": db_bytes_after_init,
            "db_bytes_final": db_bytes_final,
            "wal_bytes_final": wal_bytes_final,
            "shm_bytes_final": shm_bytes_final,
        },
        "generated_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "stdout": "\n".join(stdout_chunks),
    }


def format_int(value: Any) -> str:
    return f"{value:,}" if isinstance(value, int) else str(value)


def format_float(value: Any, digits: int = 3) -> str:
    return f"{value:.{digits}f}" if isinstance(value, (int, float)) else str(value)


def format_bytes(value: Any) -> str:
    if not isinstance(value, int):
        return str(value)
    if value >= MIB:
        return f"{value / MIB:.2f} MiB ({value:,} B)"
    if value >= 1024:
        return f"{value / 1024:.1f} KiB ({value:,} B)"
    return f"{value} B"


def pragma_summary(result: Dict[str, Any]) -> str:
    """Describe the effective pragmas, marking connection-scoped values."""
    reached = result["reached_settings"]
    parts = [
        f"journal_mode={result['pragmas'].get('journal_mode')}",
        f"synchronous={result['pragmas'].get('synchronous_name')}",
    ]
    # wal_autocheckpoint only gates WAL-triggered checkpoints, so it is
    # meaningless (and reports the default) for a rollback journal.
    if str(result["pragmas"].get("journal_mode")).lower() == "wal":
        parts.append(f"wal_autocheckpoint={reached.get('wal_autocheckpoint')}")
    return " ".join(parts)


def summary_text(result: Dict[str, Any]) -> str:
    latency = result["microseconds_per_write"]
    lines = [
        "sqlite kvtest --multitrans (OpenClaw-shaped commits)",
        f"db={result['db_path']}",
        (
            f"writes={result['writes']} payload={result['payload_bytes']}B"
            f"+-{result['payload_variance']} jmode={result['jmode']}"
        ),
        (
            "us/write: best={0} worst={1} all={2}".format(
                format_float(latency["best"]),
                format_float(latency["worst"]),
                ", ".join(format_float(value) for value in latency["all"]),
            )
        ),
        (
            f"db={format_bytes(result['files']['db_bytes_final'])} "
            f"WAL={format_bytes(result['files']['wal_bytes_final'])}"
        ),
        f"integrity={result['pragmas'].get('integrity_check')}",
        "pragmas: " + pragma_summary(result),
        "",
        "Known gaps vs OpenClaw:",
    ]
    lines.extend(f"  - {gap}" for gap in result["settings_gap"])
    lines.append("")
    lines.append(f"results: {result['out_dir']}")
    return "\n".join(lines) + "\n"


def manifest_text(result: Dict[str, Any]) -> str:
    lines = [
        f"workload: {result['workload']}",
        f"generated_at_utc: {result['generated_at_utc']}",
        f"command: {result['command']}",
        f"platform: {result['platform']}",
        f"python_version: {result['python_version']}",
        f"sqlite_version: {result['sqlite_version']}",
        f"sqlite_build_version: {result['sqlite_build_version']}",
        f"kvtest_source: {result['kvtest_source']}",
        f"amalgamation_source: {result['amalgamation_source']}",
        f"target_dir: {result['target_dir']}",
        f"db_path: {result['db_path']}",
        "openclaw_settings: " + json.dumps(result["openclaw_settings"], sort_keys=True),
        "reached_settings: " + json.dumps(result["reached_settings"], sort_keys=True),
    ]
    for entry in result["results"]:
        lines.append(f"run_{entry['index']}_argv: {shlex.join(entry['argv'])}")
    return "\n".join(lines) + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    results_dir = results_run_dir(SCRIPT_NAME, anchor=__file__)
    try:
        expand_user_paths(args)
        result = run(args)
    except BenchmarkError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    except Exception as exc:
        print(f"error: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1

    result["out_dir"] = str(results_dir)
    (Path(results_dir) / RESULT_FILENAME).write_text(
        json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    (Path(results_dir) / SUMMARY_FILENAME).write_text(
        summary_text(result), encoding="utf-8"
    )
    (Path(results_dir) / MANIFEST_FILENAME).write_text(
        manifest_text(result), encoding="utf-8"
    )
    (Path(results_dir) / STDOUT_FILENAME).write_text(
        result["stdout"], encoding="utf-8"
    )

    latency = result["microseconds_per_write"]
    print(
        "kvtest --multitrans: writes={0} payload={1}B us/write best={2} worst={3}".format(
            result["writes"],
            result["payload_bytes"],
            format_float(latency["best"]),
            format_float(latency["worst"]),
        )
    )
    print(
        "db={db} WAL={wal} integrity={integrity}".format(
            db=format_bytes(result["files"]["db_bytes_final"]),
            wal=format_bytes(result["files"]["wal_bytes_final"]),
            integrity=result["pragmas"].get("integrity_check"),
        )
    )
    print(f"target dir: {result['target_dir']}")
    print(f"results: {results_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
