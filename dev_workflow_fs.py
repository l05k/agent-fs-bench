class WorkflowError(RuntimeError):
    """A command, fixture check, or cleanup operation failed."""


@dataclass
class CommandResult:
    ms: int
    returncode: int
    stdout: str
    stderr: str


def elapsed_ms(start_ns: int) -> int:
    return (time.perf_counter_ns() - start_ns) // 1_000_000


def tail(text: str, limit: int = 4000) -> str:
    text = text.strip()
    if len(text) <= limit:
        return text
    return "..." + text[-limit:]


def ensure_ascii_source() -> None:
    data = Path(__file__).read_bytes()
    for line_number, line in enumerate(data.splitlines(), 1):
        for column, byte in enumerate(line, 1):
            if byte > 0x7F:
                raise WorkflowError(
                    f"non-ASCII byte 0x{byte:02x} at line {line_number}, "
                    f"column {column}; the script must remain ASCII-only"
                )


def terminate_process_group(
    proc: subprocess.Popen[Any],
    *,
    isolated_group: bool,
) -> None:
    if proc.poll() is not None:
        return
    if isolated_group:
        try:
            os.killpg(proc.pid, signal.SIGTERM)
        except ProcessLookupError:
            return
        except OSError:
            try:
                proc.terminate()
            except ProcessLookupError:
                return
    else:
        try:
            proc.terminate()
        except ProcessLookupError:
            return
    try:
        proc.communicate(timeout=5)
        return
    except subprocess.TimeoutExpired:
        pass
    if isolated_group:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            return
        except OSError:
            try:
                proc.kill()
            except ProcessLookupError:
                return
    else:
        try:
            proc.kill()
        except ProcessLookupError:
            return
    try:
        proc.communicate(timeout=5)
    except subprocess.TimeoutExpired:
        pass


def run_command(
    argv: list[str],
    *,
    cwd: Path,
    what: str,
    verbose: bool = False,
    capture_stdout: bool = False,
    allow_codes: tuple[int, ...] = (0,),
    extra_env: dict[str, str] | None = None,
    inherit_stdio: bool = False,
) -> CommandResult:
    env = os.environ.copy()
    env.update(
        {
            "GIT_TERMINAL_PROMPT": "0",
            "GIT_CONFIG_COUNT": "1",
            "GIT_CONFIG_KEY_0": "core.hooksPath",
            "GIT_CONFIG_VALUE_0": "/dev/null",
        }
    )
    if extra_env:
        env.update(extra_env)

    if inherit_stdio:
        stdout = None
        stderr = None
        stdin = None
    else:
        stdout = subprocess.PIPE if capture_stdout else (
            None if verbose else subprocess.DEVNULL
        )
        stderr = None if verbose else subprocess.PIPE
        stdin = subprocess.DEVNULL

    start = time.perf_counter_ns()
    isolated_group = not inherit_stdio
    try:
        proc = subprocess.Popen(
            argv,
            cwd=cwd,
            env=env,
            stdin=stdin,
            stdout=stdout,
            stderr=stderr,
            text=True,
            encoding="utf-8",
            errors="replace",
            start_new_session=isolated_group,
        )
    except OSError as exc:
        raise WorkflowError(f"{what}: cannot start {argv[0]}: {exc}") from exc

    try:
        captured_stdout, captured_stderr = proc.communicate()
    except BaseException:
        terminate_process_group(proc, isolated_group=isolated_group)
        raise

    result = CommandResult(
        ms=elapsed_ms(start),
        returncode=proc.returncode,
        stdout=captured_stdout or "",
        stderr=captured_stderr or "",
    )
    if proc.returncode not in allow_codes:
        details = []
        if result.stdout:
            details.append(f"stdout:\n{tail(result.stdout)}")
        if result.stderr:
            details.append(f"stderr:\n{tail(result.stderr)}")
        suffix = "\n" + "\n".join(details) if details else ""
        raise WorkflowError(
            f"{what} failed with exit code {proc.returncode}: "
            f"{shlex.join(argv)}{suffix}"
        )
    return result


def run_shell(command: str, *, cwd: Path, what: str, verbose: bool) -> CommandResult:
    return run_command(
        ["bash", "--noprofile", "--norc", "-c", command],
        cwd=cwd,
        what=what,
        verbose=verbose,
        extra_env={"LC_ALL": "C"},
    )


def run_git(repo: Path, args: list[str], *, what: str, verbose: bool) -> CommandResult:
    return run_command(
        ["git", "-c", "core.hooksPath=/dev/null", *args],
        cwd=repo,
        what=what,
        verbose=verbose,
    )


def git_text(
    repo: Path,
    args: list[str],
    *,
    what: str,
    allow_codes: tuple[int, ...] = (0,),
) -> str:
    result = run_command(
        ["git", "-c", "core.hooksPath=/dev/null", *args],
        cwd=repo,
        what=what,
        capture_stdout=True,
        allow_codes=allow_codes,
    )
    return result.stdout.strip()


def load_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise WorkflowError(f"cannot read fixture {path}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise WorkflowError(f"cannot parse fixture {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise WorkflowError(f"fixture {path} must contain a JSON object")
    return value


def load_commands(path: Path) -> list[str]:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise WorkflowError(f"cannot read command file {path}: {exc}") from exc

    if "%%" in lines:
        commands: list[str] = []
        current: list[str] = []
        for line in lines:
            if line == "%%":
                if current:
                    commands.append("\n".join(current) + "\n")
                    current = []
                continue
            if not current and line.lstrip().startswith("#"):
                continue
            current.append(line)
        if current:
            commands.append("\n".join(current) + "\n")
        return commands

    commands = []
    for line in lines:
        stripped = line.strip()
        if stripped and not stripped.startswith("#"):
            commands.append(stripped + "\n")
    return commands


def require_linux() -> None:
    if sys.platform.startswith("linux"):
        return
    raise WorkflowError(
        f"this workflow builds a Linux kernel and only runs on Linux "
        f"(current platform: {sys.platform})"
    )


def validate_fixtures(fixture_dir: Path) -> dict[str, Any]:
    """Fail fast on missing fixtures before the expensive Linux preparation."""
    if not fixture_dir.is_dir():
        raise WorkflowError(
            f"fixture directory not found: {fixture_dir}\n"
            "Copy data/dev-workflow next to this script, or pass --fixture-dir."
        )
    series_path = fixture_dir / DEFAULT_SERIES
    config_path = fixture_dir / DEFAULT_CONFIG
    series = load_json(series_path)
    if not config_path.is_file():
        raise WorkflowError(f"config fixture not found: {config_path}")

    base_commit = series.get("base_commit")
    commits = series.get("commits")
    if not isinstance(base_commit, str) or not base_commit:
        raise WorkflowError(f"{series_path}: invalid base_commit")
    if not isinstance(commits, list) or not commits:
        raise WorkflowError(f"{series_path}: invalid commits list")

    missing: list[str] = []
    for commit in commits:
        if not isinstance(commit, dict) or not isinstance(commit.get("id"), str):
            raise WorkflowError(f"{series_path}: invalid commit entry")
        for command_file in ("search_commands", "read_commands", "edit_commands"):
            filename = commit.get(command_file)
            if not isinstance(filename, str) or not filename:
                raise WorkflowError(
                    f"{series_path}: commit {commit['id']} has no {command_file}"
                )
            if not (fixture_dir / filename).is_file():
                missing.append(filename)
    if missing:
        raise WorkflowError(
            "fixtures reference missing command files in "
            f"{fixture_dir}: {', '.join(sorted(set(missing)))}"
        )
    return series


def missing_dependencies(*, require_fstype: bool = False) -> list[str]:
    missing = [name for name in CORE_COMMANDS if shutil.which(name) is None]
    if require_fstype and shutil.which("findmnt") is None:
        missing.append("findmnt")
    for alternatives in KERNEL_COMMANDS:
        if not any(shutil.which(name) for name in alternatives):
            missing.append(" or ".join(alternatives))
    for label, paths in KERNEL_HEADERS:
        if not any(Path(path).exists() for path in paths):
            missing.append(label)
    return missing


def available_package_manager() -> str | None:
    for manager in PACKAGE_MANAGERS:
        if shutil.which(manager):
            return manager
    return None


def install_dependencies(manager: str) -> None:
    update_cmd, install_cmd = PACKAGE_MANAGERS[manager]
    if os.geteuid() == 0:
        prefix: list[str] = []
    else:
        sudo = shutil.which("sudo")
        if not sudo:
            raise WorkflowError("dependency installation requires root or sudo")
        prefix = [sudo]

    for command in (update_cmd, install_cmd):
        if not command:
            continue
        argv = [*prefix, *command]
        print(f"Installing dependencies: {shlex.join(argv)}", file=sys.stderr)
        run_command(
            argv,
            cwd=Path("/"),
            what=f"installing dependencies with {manager}",
            inherit_stdio=True,
            extra_env={"DEBIAN_FRONTEND": "noninteractive"},
        )


def ensure_dependencies(install: bool, *, require_fstype: bool = False) -> None:
    missing = missing_dependencies(require_fstype=require_fstype)
    if missing and install:
        manager = available_package_manager()
        if manager is None:
            raise WorkflowError(
                "missing dependencies and no supported package manager was found: "
                + ", ".join(missing)
            )
        install_dependencies(manager)
        missing = missing_dependencies(require_fstype=require_fstype)

    if missing:
        raise WorkflowError(
            "missing dependencies: "
            + ", ".join(missing)
            + "\nRerun with --install-deps or install them manually."
        )
    print("Dependency check passed.", file=sys.stderr)


def clear_directory(path: Path) -> None:
    for child in path.iterdir():
        if child.is_dir() and not child.is_symlink():
            shutil.rmtree(child)
        else:
            child.unlink()


def cleanup_failed_clone(repo: Path, *, preserve_root: bool) -> None:
    if not repo.exists():
        return
    if preserve_root:
        clear_directory(repo)
    else:
        shutil.rmtree(repo)


def resolve_commit(repo: Path, revision: str) -> str | None:
    """Resolve a revision expression (e.g. ``<sha>^``) to a full commit id.

    ``rev-parse --verify --quiet`` exits 1 for anything it cannot resolve, so
    missing objects stay a "not present" answer instead of an error.
    """
    result = run_command(
        [
            "git",
            "-c",
            "core.hooksPath=/dev/null",
            "rev-parse",
            "--verify",
            "--quiet",
            f"{revision}^{{commit}}",
        ],
        cwd=repo,
        what=f"resolving commit {revision}",
        capture_stdout=True,
        allow_codes=(0, 1),
    )
    return result.stdout.strip() or None


def has_local_commit(repo: Path, revision: str) -> bool:
    return resolve_commit(repo, revision) is not None


def prepare_linux_checkout(
    repo: Path,
    *,
    linux_url: str,
    base_commit: str,
    commit_ids: list[str],
    verbose: bool,
) -> str:
    if repo == Path("/"):
        raise WorkflowError("refusing to use / as --repo")

    action = "reused"
    preserve_root = False
    needs_clone = not repo.exists()
    if repo.exists():
        if not repo.is_dir():
            raise WorkflowError(f"--repo is not a directory: {repo}")
        if any(repo.iterdir()):
            if not (repo / ".git").exists():
                raise WorkflowError(
                    f"--repo is non-empty but is not a Git checkout: {repo}"
                )
        else:
            # An empty directory is kept when it is a mountpoint (it cannot be
            # removed, and removing it would drop the filesystem under test).
            # ``git clone`` accepts an existing empty directory, so the clone
            # still happens either way.
            preserve_root = os.path.ismount(repo)
            needs_clone = True
            if not preserve_root:
                repo.rmdir()

    if needs_clone:
        repo.parent.mkdir(parents=True, exist_ok=True)
        source = Path(linux_url).expanduser()
        clone_source = str(source.resolve()) if source.exists() else linux_url
        print(f"Cloning Linux into {repo} from {clone_source}...", file=sys.stderr)
        try:
            run_command(
                ["git", "clone", clone_source, str(repo)],
                cwd=repo.parent,
                what="cloning Linux checkout",
                verbose=True,
            )
        except BaseException as exc:
            try:
                cleanup_failed_clone(repo, preserve_root=preserve_root)
            except OSError as cleanup_exc:
                raise WorkflowError(
                    f"Linux clone failed and partial checkout cleanup failed: "
                    f"{cleanup_exc}"
                ) from exc
            raise
        action = "cloned"

    required = [base_commit, *commit_ids]
    if not all(has_local_commit(repo, revision) for revision in required):
        print(
            "Fetching missing Linux fixture commits. This is preparation, not timing.",
            file=sys.stderr,
        )
        run_git(
            repo,
            ["fetch", "--tags", "origin"],
            what="fetching required Linux commits",
            verbose=True,
        )
    missing = [revision for revision in required if not has_local_commit(repo, revision)]
    if missing:
        raise WorkflowError(
            "Linux checkout is missing required fixture commits after fetch: "
            + ", ".join(missing)
        )

    run_git(
        repo,
        ["clean", "-fdx"],
        what="cleaning checkout before preparation checkout",
        verbose=verbose,
    )
    run_git(
        repo,
        ["checkout", "--detach", "--force", base_commit],
        what="checking out fixture base commit",
        verbose=verbose,
    )
    run_git(
        repo,
        ["clean", "-fdx"],
        what="removing untracked preparation artifacts",
        verbose=verbose,
    )
    return action


def validate_repository(
    repo: Path,
    *,
    base_commit: str,
    commit_ids: list[str],
) -> None:
    if not repo.exists() or not repo.is_dir():
        raise WorkflowError(f"--repo is not a directory: {repo}")

    top_level = Path(
        git_text(
            repo,
            ["rev-parse", "--show-toplevel"],
            what="checking repository root",
        )
    ).resolve()
    if top_level != repo.resolve():
        raise WorkflowError(
            f"--repo must be the root of the Linux checkout, but its Git root is {top_level}"
        )

    shallow = git_text(
        repo,
        ["rev-parse", "--is-shallow-repository"],
        what="checking whether the fixture is shallow",
    )
    if shallow != "false":
        raise WorkflowError(
            f"checkout is shallow ({shallow}); a full Linux clone is required"
        )

    promisor = git_text(
        repo,
        ["config", "--bool", "--get", "remote.origin.promisor"],
        what="checking promisor configuration",
        allow_codes=(0, 1),
    )
    if promisor == "true":
        raise WorkflowError(
            "checkout is a partial clone; lazy object fetches could use the network"
        )

    partial = git_text(
        repo,
        ["config", "--get", "extensions.partialClone"],
        what="checking partial clone configuration",
        allow_codes=(0, 1),
    )
    if partial:
        raise WorkflowError(
            "checkout has extensions.partialClone; lazy fetches are not allowed"
        )

    sparse = git_text(
        repo,
        ["config", "--bool", "--get", "core.sparseCheckout"],
        what="checking sparse-checkout configuration",
        allow_codes=(0, 1),
    )
    if sparse == "true":
        raise WorkflowError("checkout uses sparse-checkout; a complete Linux tree is required")

    required = [base_commit, *commit_ids]
    for revision in required:
        run_git(
            repo,
            ["rev-parse", "--verify", f"{revision}^{{commit}}"],
            what=f"verifying local object for {revision}",
            verbose=False,
        )


def detect_filesystem(path: Path) -> str | None:
    findmnt = shutil.which("findmnt")
    if not findmnt:
        return None
    proc = subprocess.run(
        [findmnt, "-T", str(path), "-n", "-o", "FSTYPE"],
        text=True,
        encoding="utf-8",
        errors="replace",
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        check=False,
    )
    value = proc.stdout.strip()
    return value or None


def existing_ancestor(path: Path) -> Path:
    probe = path
    while not probe.exists() and probe != probe.parent:
        probe = probe.parent
    return probe


def require_filesystem(path: Path, expected: str | None, label: str) -> None:
    if not expected:
        return
    probe = existing_ancestor(path)
    actual = detect_filesystem(probe)
    if actual is None:
        raise WorkflowError(
            f"cannot determine filesystem for {label}; install findmnt or "
            "remove the filesystem requirement"
        )
    if actual != expected:
        raise WorkflowError(
            f"{label} must be on {expected}, but {probe} is on {actual}"
        )


def active_marker_path(repo: Path) -> Path:
    git_dir = Path(
        git_text(
            repo,
            ["rev-parse", "--absolute-git-dir"],
            what="resolving Git directory",
        )
    )
    return git_dir / ACTIVE_MARKER


def marker_owner_is_running(marker: Path) -> bool:
    try:
        first_line = marker.read_text(encoding="ascii").splitlines()[0]
        pid = int(first_line)
    except (OSError, ValueError, IndexError):
        return False
    if pid == os.getpid():
        return False
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def cleanup_checkout(
    repo: Path,
    *,
    base_commit: str,
    marker: Path,
    verbose: bool,
) -> None:
    errors: list[str] = []
    try:
        run_git(
            repo,
            ["reset", "--hard", base_commit],
            what="restoring checkout to fixture base commit",
            verbose=verbose,
        )
    except WorkflowError as exc:
        errors.append(str(exc))
    try:
        run_git(
            repo,
            ["clean", "-fdx"],
            what="removing generated and untracked files",
            verbose=verbose,
        )
    except WorkflowError as exc:
        errors.append(str(exc))

    if not errors:
        try:
            marker.unlink(missing_ok=True)
        except OSError as exc:
            errors.append(f"cannot remove ownership marker {marker}: {exc}")

    if errors:
        raise WorkflowError("cleanup failed: " + "; ".join(errors))


def begin_checkout_run(
    repo: Path,
    *,
    base_commit: str,
    marker: Path,
    verbose: bool,
) -> None:
    if marker.exists():
        if marker_owner_is_running(marker):
            raise WorkflowError(
                f"another dev-workflow run owns this checkout: {marker}"
            )
        print(
            f"Recovering checkout after an interrupted run: {repo}",
            file=sys.stderr,
        )
        cleanup_checkout(
            repo,
            base_commit=base_commit,
            marker=marker,
            verbose=verbose,
        )

    head = git_text(repo, ["rev-parse", "HEAD"], what="reading checkout HEAD")
    expected = resolve_commit(repo, base_commit)
    if expected is None:
        raise WorkflowError(
            f"fixture base commit {base_commit} is not present in {repo}"
        )
    if head != expected:
        raise WorkflowError(
            f"checkout HEAD is {head}, expected fixture base commit "
            f"{base_commit} ({expected})"
        )

    status = git_text(
        repo,
        [
            "status",
            "--porcelain=v1",
            "--untracked-files=all",
            "--ignored",
        ],
        what="checking checkout cleanliness",
    )
    if status:
        preview = "\n".join(status.splitlines()[:20])
        raise WorkflowError(
            "checkout must be clean before a new run, including ignored and "
            f"untracked files:\n{preview}"
        )

    marker.write_text(f"{os.getpid()}\n{time.time_ns()}\n", encoding="ascii")


def verify_tree(repo: Path, commit_id: str) -> dict[str, Any]:
    actual = git_text(
        repo,
        ["rev-parse", "HEAD^{tree}"],
        what=f"reading replayed tree for {commit_id}",
    )
    expected = git_text(
        repo,
        ["rev-parse", f"{commit_id}^{{tree}}"],
        what=f"reading target tree for {commit_id}",
    )
    if actual != expected:
        raise WorkflowError(
            f"tree mismatch for {commit_id}: expected {expected}, got {actual}"
        )
    return {"commit": commit_id, "tree": actual, "ok": True}


def record_checkpoint(step: int, phase: str, steps: list[dict[str, Any]]) -> None:
    steps.append({"step": f"checkpoint: {phase}", "ms": 0})


def write_result(results_dir: Path, result: dict[str, Any]) -> None:
    output = results_dir / "result.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(result, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(f"Results written to {output}", file=sys.stderr)


def run_workflow(args: argparse.Namespace) -> dict[str, Any]:
    repo = Path(args.repo).expanduser().absolute()
    fixture_dir = Path(args.fixture_dir).expanduser().absolute()
    series_path = fixture_dir / DEFAULT_SERIES
    config_path = fixture_dir / DEFAULT_CONFIG

    series = validate_fixtures(fixture_dir)
    base_commit_expression = series["base_commit"]
    commits = series["commits"]
    commit_ids = [commit["id"] for commit in commits]

    require_filesystem(repo, args.require_fstype, "Linux checkout")
    preparation_start = time.perf_counter_ns()
    repo_action = prepare_linux_checkout(
        repo,
        linux_url=args.linux_url,
        base_commit=base_commit_expression,
        commit_ids=commit_ids,
        verbose=args.verbose,
    )
    validate_repository(
        repo, base_commit=base_commit_expression, commit_ids=commit_ids
    )
    # The fixture may name its base with a revision expression (the shipped
    # dev-workflow fixture uses ``c2c54b5f34f6^``). Everything after this point
    # compares full object ids, so resolve once here.
    base_commit = resolve_commit(repo, base_commit_expression)
    if base_commit is None:
        raise WorkflowError(
            f"fixture base commit {base_commit_expression} cannot be resolved "
            f"in {repo}"
        )
    marker = active_marker_path(repo)

    if args.jobs > 0:
        jobs = args.jobs
    else:
        try:
            jobs = len(os.sched_getaffinity(0))
        except (AttributeError, OSError):
            jobs = os.cpu_count() or 1

    steps: list[dict[str, Any]] = []
    assertions: list[dict[str, Any]] = []
    checkpoint_step = 0
    cleanup_error: str | None = None
    cleanup_ms: int | None = None
    preparation_ms: int | None = None
    workflow_ms: int | None = None
    success = False
    error: str | None = None
    timed_start: int | None = None
    # Cleanup must only touch a checkout this process claimed; an abort such as
    # "another run owns this checkout" must not reset the owner's work.
    owns_marker = False

    try:
        begin_checkout_run(
            repo,
            base_commit=base_commit,
            marker=marker,
            verbose=args.verbose,
        )
        owns_marker = True
        preparation_ms = elapsed_ms(preparation_start)
        print(
            f"Linux preparation complete ({repo_action}, {preparation_ms} ms).",
            file=sys.stderr,
        )
        timed_start = time.perf_counter_ns()

        config_start = time.perf_counter_ns()
        make = ["make"]
        run_command(
            [*make, "tinyconfig", f"-j{jobs}"],
            cwd=repo,
            what="make tinyconfig",
            verbose=args.verbose,
        )
        try:
            shutil.copyfile(config_path, repo / ".config")
        except OSError as exc:
            raise WorkflowError(f"cannot install config fixture {config_path}: {exc}") from exc
        run_command(
            [*make, "olddefconfig"],
            cwd=repo,
            what="make olddefconfig",
            verbose=args.verbose,
        )
        steps.append({"step": "config: tinyconfig", "ms": elapsed_ms(config_start)})

        checkpoint_step += 1
        record_checkpoint(checkpoint_step, "config", steps)

        initial = run_command(
            [*make, f"-j{jobs}"],
            cwd=repo,
            what="initial build",
            verbose=args.verbose,
        )
        steps.append({"step": "initial-build: make", "ms": initial.ms})

        checkpoint_step += 1
        record_checkpoint(checkpoint_step, "initial-build", steps)

        for commit in commits:
            commit_id = commit["id"]
            message = commit.get("message")
            files = commit.get("files")
            if not isinstance(message, str):
                raise WorkflowError(f"{series_path}: commit {commit_id} has no message")
            if not isinstance(files, list) or not all(isinstance(f, str) for f in files):
                raise WorkflowError(f"{series_path}: commit {commit_id} has invalid files")

            commands: list[tuple[str, str]] = []
            for command_file in ("search_commands", "read_commands", "edit_commands"):
                filename = commit.get(command_file)
                if not isinstance(filename, str) or not filename:
                    raise WorkflowError(
                        f"{series_path}: commit {commit_id} has no {command_file}"
                    )
                commands.append((command_file, filename))

            for phase, filename in commands:
                category = phase.removesuffix("_commands")
                for idx, command in enumerate(load_commands(fixture_dir / filename), 1):
                    result = run_shell(
                        command,
                        cwd=repo,
                        what=f"{category} command for {commit_id} #{idx}",
                        verbose=args.verbose,
                    )
                    steps.append(
                        {"step": f"{category}: {commit_id} #{idx}", "ms": result.ms}
                    )
                    if category == "edit":
                        checkpoint_step += 1
                        record_checkpoint(
                            checkpoint_step, f"{commit_id} #{idx}", steps
                        )

            incremental = run_command(
                [*make, f"-j{jobs}"],
                cwd=repo,
                what=f"incremental build for {commit_id}",
                verbose=args.verbose,
            )
            steps.append(
                {"step": f"incremental-build: {commit_id}", "ms": incremental.ms}
            )

            checkpoint_step += 1
            record_checkpoint(
                checkpoint_step, f"incremental-build {commit_id}", steps
            )

            status = run_git(
                repo,
                ["status", "--short"],
                what=f"git status for {commit_id}",
                verbose=args.verbose,
            )
            steps.append({"step": f"git-status: {commit_id}", "ms": status.ms})

            diff = run_git(
                repo,
                ["diff", "--stat", "--", *files],
                what=f"git diff for {commit_id}",
                verbose=args.verbose,
            )
            steps.append({"step": f"git-diff: {commit_id}", "ms": diff.ms})

            add = run_git(
                repo,
                ["add", "--", *files],
                what=f"git add for {commit_id}",
                verbose=args.verbose,
            )
            steps.append({"step": f"git-add: {commit_id}", "ms": add.ms})

            commit_result = run_git(
                repo,
                [
                    "-c",
                    "user.name=YoloFS Bench",
                    "-c",
                    "user.email=bench@yolo.local",
                    "commit",
                    "--no-gpg-sign",
                    "-m",
                    message,
                ],
                what=f"git commit for {commit_id}",
                verbose=args.verbose,
            )
            steps.append({"step": f"git-commit: {commit_id}", "ms": commit_result.ms})

            checkpoint_step += 1
            record_checkpoint(checkpoint_step, f"git-commit {commit_id}", steps)
            assertions.append(verify_tree(repo, commit_id))

        success = True
    except WorkflowError as exc:
        error = str(exc)
    except KeyboardInterrupt:
        error = "interrupted"
    except Exception as exc:
        error = f"unexpected error: {exc}"
        if args.verbose:
            traceback.print_exc()
    finally:
        if preparation_ms is None:
            preparation_ms = elapsed_ms(preparation_start)
        if timed_start is not None:
            workflow_ms = elapsed_ms(timed_start)
        else:
            workflow_ms = 0
        cleanup_start = time.perf_counter_ns()
        if owns_marker:
            try:
                cleanup_checkout(
                    repo,
                    base_commit=base_commit,
                    marker=marker,
                    verbose=args.verbose,
                )
            except WorkflowError as exc:
                cleanup_error = str(exc)
        cleanup_ms = elapsed_ms(cleanup_start)

    if cleanup_error:
        success = False
        error = (
            f"{error}; {cleanup_error}"
            if error
            else cleanup_error
        )

    return {
        "schema_version": 3,
        "workflow": "dev-workflow",
        "execution_mode": "single-checkout",
        "success": success,
        "error": error,
        "repo": str(repo),
        "repo_action": repo_action,
        "preparation_ms": preparation_ms,
        "fixture_dir": str(fixture_dir),
        "series": str(series_path),
        "checkout_cleaned": not marker.exists(),
        "filesystem": detect_filesystem(repo),
        "required_filesystem": args.require_fstype,
        "base_commit": base_commit,
        "checkpoint_count": checkpoint_step,
        "jobs": jobs,
        "elapsed_ms": workflow_ms,
        "cleanup_ms": cleanup_ms,
        "steps": steps,
        "tree_assertions": assertions,
    }


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run dev-workflow directly in one disposable Linux checkout on the "
            "filesystem under test."
        )
    )
    parser.add_argument(
        "--repo",
        required=True,
        help=(
            "disposable Linux checkout path on the filesystem under test; "
            "cloned from --linux-url if absent and reset/cleaned after each run"
        ),
    )
    parser.add_argument(
        "--linux-url",
        default=DEFAULT_LINUX_URL,
        help=(
            "Git URL or local path used only when --repo does not exist "
            "(default: %(default)s)"
        ),
    )
    parser.add_argument(
        "--fixture-dir",
        default=str(DEFAULT_FIXTURE_DIR),
        help="directory containing the checked-in workflow fixtures",
    )
    parser.add_argument(
        "--require-fstype",
        default=None,
        help="require this filesystem type for --repo, for example ext4",
    )
    parser.add_argument(
        "--install-deps",
        action="store_true",
        help="install missing build dependencies before running",
    )
    parser.add_argument(
        "--jobs",
        type=int,
        default=0,
        help="build parallelism (default: available CPUs)",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="show command output",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    results_dir = results_run_dir(SCRIPT_NAME, anchor=__file__)

    try:
        ensure_ascii_source()
        validate_fixtures(Path(args.fixture_dir).expanduser().absolute())
        require_linux()
        ensure_dependencies(
            args.install_deps,
            require_fstype=bool(args.require_fstype),
        )
        result = run_workflow(args)
    except WorkflowError as exc:
        result = {
            "schema_version": 3,
            "workflow": "dev-workflow",
            "success": False,
            "error": str(exc),
        }
    except KeyboardInterrupt:
        result = {
            "schema_version": 3,
            "workflow": "dev-workflow",
            "success": False,
            "error": "interrupted",
        }
    except Exception as exc:
        result = {
            "schema_version": 3,
            "workflow": "dev-workflow",
            "success": False,
            "error": f"unexpected error: {exc}",
        }

    write_result(results_dir, result)
    if result.get("success"):
        print(
            "dev-workflow completed: "
            f"{result.get('elapsed_ms', 0)} ms, "
            f"{len(result.get('steps', []))} steps, "
            f"{result.get('checkpoint_count', 0)} checkpoint boundaries"
        )
        return 0

    print(f"dev-workflow failed: {result.get('error')}", file=sys.stderr)
    return 1


def _handle_sigterm(_signum: int, _frame: Any) -> None:
    raise KeyboardInterrupt


if __name__ == "__main__":
    signal.signal(signal.SIGTERM, _handle_sigterm)
    raise SystemExit(main())
