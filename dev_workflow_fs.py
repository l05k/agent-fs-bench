#!/usr/bin/env python3
"""Run the dev-workflow directly in one Linux checkout.

This script is self-contained: it depends only on the Python standard library
and on the fixtures checked in next to it under
``data/dev-workflow/overlayfs-ovl-file.json`` (including the associated
``*-search.cmds``, ``*-read.cmds`` and ``*-edit.cmds`` files). Copy this script
together with ``data/dev-workflow/`` to run it outside any surrounding
repository; ``--fixture-dir`` can point at an alternative fixture location.
No network access is needed for fixtures, and no external checkout of the
upstream project is consulted.

Compared with the backend-checkpoint workflow it was derived from, this variant
deliberately removes ckpt/backend operations: it uses one checkout on the
filesystem under test and records checkpoint boundaries as zero-cost markers
only. Consequently, its timings must not be compared with backend checkpoint
measurements.

The checkout passed with --repo must be disposable and located (or created) on
the filesystem under test. If it does not exist, the script clones Linux into
that exact path during preparation. It never creates a second Git worktree.
The timed config/build/search/edit/commit sequence runs in that one checkout,
which is then restored with `git reset --hard` and `git clean -fdx`.

Note that the fixture commits are pinned to the upstream Linux history, so the
``--repo`` checkout (or its ``--linux-url`` remote) must contain those objects.
The script is Linux-only: it builds a Linux kernel and checks for Linux build
tooling and headers during the dependency check.

An ownership marker in the Git directory allows the next invocation to recover
from a previous run that was interrupted before cleanup. Checkpoint boundaries
are recorded as no-ops; no YoloFS or overlayfs checkpoint backend is required.

Review notes / known limitations:

* ``git clean -fdx`` is destructive and can delete ignored or untracked files
    before the run's cleanliness check; ``--repo`` must therefore be disposable.
* The ownership-marker check and write are not atomic, so concurrent runs can
    race on the same checkout.
* An interruption during checkout preparation can occur before the marker is
    written, leaving the checkout modified without automatic recovery.
* Reusing a checkout can preserve build-cache state, so preparation and cache
    conditions are not equivalent to a fresh worktree run.
* Shell fixture pipelines are not run with ``pipefail``.
"""

